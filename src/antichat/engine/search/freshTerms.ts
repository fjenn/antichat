/**
 * Knowledge cutoffs by model-name prefix ("YYYY-MM"). [ASSUMPTION] as on the
 * Mac: the month before the family's first public release, until the model
 * catalogue (M5) states one.
 */
export const KNOWLEDGE_CUTOFFS: Array<[RegExp, string]> = [
  [/gemma[-_ ]?4/i, '2026-03'],
  [/qwen[-_ ]?3\.5/i, '2026-01'],
  [/lfm[-_ ]?3/i, '2026-06'],
];
export const DEFAULT_CUTOFF = '2025-12';

export function knowledgeCutoffFor(modelName?: string): string {
  for (const [pattern, cutoff] of KNOWLEDGE_CUTOFFS) {
    if (modelName && pattern.test(modelName)) {
      return cutoff;
    }
  }
  return DEFAULT_CUTOFF;
}
