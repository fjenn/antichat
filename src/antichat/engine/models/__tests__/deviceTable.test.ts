import fs from 'fs';
import path from 'path';

import {bundledCatalog} from '../catalog/bundledCatalog';
import {getClass} from '../catalog/lookup';
import {classifyDevice} from '../device/classify';
import {selectModel, selectUnrestricted} from '../policy/select';

import {PhoneCase, PHONES} from './fixtures/phones';

/**
 * The policy at a glance: about thirty real phones, each with the class and
 * model it must get. The same rows are printed to docs/antichat/m5-device-table.md;
 * run with UPDATE_DEVICE_TABLE=1 to rewrite that file after a policy change.
 */

const DOC = path.resolve(
  __dirname,
  '../../../../../docs/antichat/m5-device-table.md',
);

const decide = (phone: PhoneCase) => {
  const device = classifyDevice(phone.snapshot, bundledCatalog);
  return {
    device,
    selection: selectModel(device, bundledCatalog),
    unrestricted: selectUnrestricted(device, bundledCatalog),
  };
};

describe('device -> model table', () => {
  it('covers about thirty phones on both platforms', () => {
    expect(PHONES.length).toBeGreaterThanOrEqual(30);
    expect(new Set(PHONES.map(p => p.name)).size).toBe(PHONES.length);
    expect(PHONES.some(p => p.snapshot.platform === 'android')).toBe(true);
    expect(PHONES.some(p => p.basis === 'measured')).toBe(true);
  });

  it.each(PHONES.map(phone => [phone.name, phone] as const))(
    '%s',
    (_name, phone) => {
      const {device, selection, unrestricted} = decide(phone);
      expect({
        deviceClass: device.deviceClass,
        modelId: selection.model.id,
        contextSize: selection.shape.contextSize,
        vision: selection.shape.vision,
        unrestrictedId: unrestricted?.model.id ?? null,
        upgradeOfferId: selection.upgradeOffer?.model.id,
      }).toEqual({upgradeOfferId: undefined, ...phone.expected});
      // Every phone in the table gets its class default, and it fits.
      expect(selection.reason).toBe('class_default');
      expect(selection.fit.fits).toBe(true);
      expect(selection.model.id).toBe(
        getClass(bundledCatalog, device.deviceClass).defaultModel,
      );
    },
  );

  it('never gives a phone a class above its marketed RAM', () => {
    const order = ['A', 'B', 'C', 'D', 'E'];
    for (const phone of PHONES) {
      const marketedClass = [...bundledCatalog.classes]
        .reverse()
        .find(c => c.marketedRamGb <= phone.marketedRamGb)!;
      expect(order.indexOf(phone.expected.deviceClass)).toBeLessThanOrEqual(
        order.indexOf(marketedClass.id),
      );
    }
  });

  it('matches docs/antichat/m5-device-table.md', () => {
    const rendered = renderTable();
    if (process.env.UPDATE_DEVICE_TABLE) {
      fs.mkdirSync(path.dirname(DOC), {recursive: true});
      fs.writeFileSync(DOC, rendered);
    }
    expect(fs.readFileSync(DOC, 'utf8')).toBe(rendered);
  });
});

const gb = (bytes: number): string => (bytes / 1000 ** 3).toFixed(2);

function row(phone: PhoneCase): string {
  const {device, selection, unrestricted} = decide(phone);
  const budget = device.budget;
  const reading =
    budget.source === 'measured'
      ? `${gb(budget.measuredAvailableBytes)} GB`
      : `${gb(budget.measuredAvailableBytes)} GB, floor ${gb(
          budget.availableBytes,
        )} GB`;
  const gpu =
    device.gpu.backend === 'cpu'
      ? `CPU (${device.gpu.reason})`
      : device.gpu.backend === 'metal'
        ? 'Metal'
        : `OpenCL, ${device.gpu.maxGpuLayers} layers`;
  return [
    phone.name,
    `${phone.marketedRamGb} GB`,
    phone.chip,
    `${reading} (${phone.basis})`,
    `**${device.deviceClass}**`,
    `**${selection.model.displayName}**`,
    `${gb(selection.downloadBytes)} GB`,
    String(selection.shape.contextSize),
    selection.shape.vision ? 'yes' : 'OCR',
    gpu,
    unrestricted?.model.displayName.replace(' Unrestricted', '') ?? 'none',
    selection.upgradeOffer?.model.displayName ?? '',
    phone.note ?? '',
  ].join(' | ');
}

function renderTable(): string {
  const classes = bundledCatalog.classes
    .map(c => {
      const features = c.features;
      const on = (flag: boolean) => (flag ? 'yes' : 'no');
      return [
        c.id,
        `${c.marketedRamGb} GB`,
        c.defaultModel,
        String(c.contextSize),
        on(features.vision),
        on(features.imageGeneration),
        on(features.voiceMode),
        on(features.embeddings),
        c.unrestrictedModel ?? 'none',
        c.upgrade ? `${c.upgrade.modelId} (${c.upgrade.mode})` : '',
      ].join(' | ');
    })
    .map(line => `| ${line} |`);
  const phones = PHONES.map(phone => `| ${row(phone)} |`);
  return [
    '# M5: device -> model table',
    '',
    'Generated by `src/antichat/engine/models/__tests__/deviceTable.test.ts` from the',
    `bundled catalogue (serial ${bundledCatalog.serial}). Do not edit by hand:`,
    '',
    '    UPDATE_DEVICE_TABLE=1 yarn jest src/antichat/engine/models/__tests__/deviceTable.test.ts --coverage=false',
    '',
    'The test fails when this file and the policy disagree.',
    '',
    '## How a phone gets its class',
    '',
    '- The class comes from the memory **read at launch**, not from the RAM on the box.',
    '  iPhone: model file + projector must fit 55% of physical RAM (the weights are',
    '  memory-mapped), and the KV cache + buffers must fit 50% of what',
    '  `os_proc_available_memory()` reports. Android: everything must fit one pool,',
    '  the larger of `availMem` and a share of total RAM (the fix for PocketPal #982).',
    "- PocketPal's chip tables cap the class, so a slow chip with a lot of RAM does",
    '  not get a model it cannot run at a usable speed.',
    '- The phone gets the lower of the two.',
    '',
    '## Classes',
    '',
    '| Class | Typical RAM | Default model | Context | Vision | Image generation | Voice mode | Embeddings beside chat | Unrestricted add-on | Upgrade |',
    '|---|---|---|---|---|---|---|---|---|---|',
    ...classes,
    '',
    '## Phones',
    '',
    'Launch memory: `measured` = read on the device by our spike; `published` = a',
    'figure measured by someone else (research doc 03, section 2); `assumed` = no',
    'measurement exists yet. "floor" means the reading was missing or too low and',
    'the floor was used instead.',
    '',
    '| Phone | RAM | Chip | Launch memory | Class | Model | Download | Context | Images | Backend | Unrestricted add-on | Upgrade offered | Note |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|---|',
    ...phones,
    '',
  ].join('\n');
}
