@testable import AntiChatStorage

let schemaSnapshotURL = repoRoot.appendingPathComponent("Packages/Storage/Schema/v1_core.sql")

/// The migrated schema as executable DDL: every `sqlite_master` statement except SQLite internals and the FTS5
/// shadow tables (which `CREATE VIRTUAL TABLE` makes by itself), in creation order. `chunk_vec*` (vec0 + its shadow
/// tables and trigger) is excluded: plain SQLite cannot execute vec0, and AppDatabase ensures it (M2.T16).
func schemaDump(_ db: Database) throws -> String {
    let rows = try Row.fetchAll(db, sql: """
        SELECT name, sql FROM sqlite_master
        WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'
          AND name NOT GLOB '*_fts_data' AND name NOT GLOB '*_fts_idx' AND name NOT GLOB '*_fts_docsize'
          AND name NOT GLOB '*_fts_config' AND name NOT GLOB '*_fts_content'
          AND name NOT GLOB 'chunk_vec*'
        ORDER BY rowid
        """)
    let header = """
        -- Frozen DDL of the AntiChat v1 schema after migration `v1_core` (generated by MigrationV1Tests from a
        -- migrated database; do not edit by hand). Executed by tools/fixtures/gen-chats.py; checked by
        -- MigrationV1Tests/schemaMatchesSnapshot. A new migration regenerates it with ANTICHAT_UPDATE_SCHEMA_SNAPSHOT=1.

        """
    return header + rows.map { "\($0["sql"] as String);" }.joined(separator: "\n\n") + "\n"
}

@Suite("MigrationV1Tests") struct MigrationV1Tests {
    @Test func schemaMatchesSnapshot() throws {
        let dump = try AppDatabase.inMemory().read(schemaDump)
        if ProcessInfo.processInfo.environment["ANTICHAT_UPDATE_SCHEMA_SNAPSHOT"] == "1" {
            try FileManager.default.createDirectory(at: schemaSnapshotURL.deletingLastPathComponent(),
                                                    withIntermediateDirectories: true)
            try dump.write(to: schemaSnapshotURL, atomically: true, encoding: .utf8)
        }
        let snapshot = try String(contentsOf: schemaSnapshotURL, encoding: .utf8)
        #expect(dump == snapshot, "schema drifted from Packages/Storage/Schema/v1_core.sql")
    }

