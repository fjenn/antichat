    @Test func onDiskPoolPragmas() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("antichat-m1t04-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: dir) }
        let database = try AppDatabase.onDisk(at: dir.appendingPathComponent("antichat.sqlite"))
        #expect(database.writer is DatabasePool)
        #expect(!database.isInMemory)
        try database.read { (db: Database) throws in
            #expect(try String.fetchOne(db, sql: "PRAGMA journal_mode") == "wal")
            #expect(try Int.fetchOne(db, sql: "PRAGMA foreign_keys") == 1)
            #expect(try Int.fetchOne(db, sql: "PRAGMA synchronous") == 1)  // NORMAL
        }
        // Re-opening an up-to-date file is a no-op migration.
        _ = try AppDatabase.onDisk(at: dir.appendingPathComponent("antichat.sqlite"))
    }

