// AT-296 leg (schema) (M1.T04): `v1_core` creates exactly the frozen schema `Packages/Storage/Schema/v1_core.sql`,
// the on-disk pool runs WAL with foreign keys and synchronous=NORMAL, FTS5 indexes text parts only and follows
// updates/deletes, the newer-version guard refuses a superseded file, and the records/repositories round-trip.
// Set ANTICHAT_UPDATE_SCHEMA_SNAPSHOT=1 to rewrite the snapshot after an intentional (new-migration) change.
import AntiChatFoundation
