    @Test func fullTextIndexesTextPartsOnly() throws {
        let f = try TreeFixtures.treeBasic()
        let messages = MessageRepository(f.database)
        try messages.upsertPart(f.ids[5], idx: 1, PartContent(kind: .reasoning, body: "secretreasoning"))
        try messages.upsertPart(f.ids[5], idx: 2, .text("the zebracorn appears"))
        #expect(try messages.search("zebracorn").map(\.messageID) == [f.ids[5]])
        #expect(try messages.search("secretreasoning").isEmpty)
        #expect(try messages.search("zebra").map(\.chatID) == [f.chatID])  // prefix match
        // Streaming upsert replaces the indexed text.
        try messages.upsertPart(f.ids[5], idx: 2, .text("now a unicorn"))
        #expect(try messages.search("zebracorn").isEmpty)
        #expect(try messages.search("unicorn").count == 1)
        // Kind change text → reasoning drops it from the index.
        try messages.upsertPart(f.ids[5], idx: 2, PartContent(kind: .reasoning, body: "now a unicorn"))
        #expect(try messages.search("unicorn").isEmpty)
        // Deleting the chat cascades to parts and the FTS rows.
        try ChatRepository(f.database).delete(f.chatID)
        #expect(try messages.search("question").isEmpty)
        try f.database.read { (db: Database) throws in
            #expect(try Int.fetchOne(db, sql: "SELECT COUNT(*) FROM message_part") == 0)
        }
        #expect(try f.database.repairFullTextIfNeeded() == false)
        #expect(try messages.search("").isEmpty)
    }

    @Test func fullTextRebuildRepairsDrift() throws {
        let f = try TreeFixtures.treeBasic()
        // Simulate drift: a part changed with the triggers bypassed.
        try f.database.write { (db: Database) throws in
            try db.execute(sql: "DROP TRIGGER message_part_fts_au")
            try db.execute(sql: "UPDATE message_part SET body = 'drifted' WHERE message_id = ?", arguments: [f.ids[0]])
