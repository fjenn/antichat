    @Test func streamingFlushFinishAndCrashRecovery() throws {
        let f = try TreeFixtures.treeBasic()
        let tree = MessageTree(f.database)
        let messages = MessageRepository(f.database)
        let reply = try tree.append(chatID: f.chatID, parentID: f.ids[5], role: .assistant, status: .pending)
        try messages.flush(reply.id, parts: [(0, .text("partial"))])
        #expect(try messages.message(reply.id)?.status == .streaming)
        #expect(try messages.markInterruptedAfterCrash() == [reply.id])
        #expect(try messages.message(reply.id)?.status == .interrupted)
        #expect(try messages.markInterruptedAfterCrash() == [])
        let provenance = MessageProvenance(modelSHA: "sha256-x", mode: .normal, sampling: ["temperature": 0.2],
                                           tokPerS: 50.5, searchSources: ["https://example.org"], skill: "none")
        try messages.finish(reply.id, status: .done, parts: [(0, .text("full reply"))],
                            usage: MessageUsage(promptTokens: 1, completionTokens: 2, cachedTokens: 0, ttftMs: 120),
                            provenance: provenance)
        let done = try #require(try messages.message(reply.id))
        #expect(done.status == .done)
        #expect(done.provenance == provenance)
        #expect(done.usage?.ttftMs == 120)
        #expect(try messages.parts(of: reply.id).map(\.body) == ["full reply"])
        // R-234: provenance_json carries model_sha, mode, sampling_json and tok_per_s.
        let json = try f.database.read { (db: Database) throws in
            try String.fetchOne(db, sql: "SELECT provenance_json FROM message WHERE id = ?", arguments: [reply.id])
        }
        for key in ["model_sha", "mode", "sampling_json", "tok_per_s"] {
            #expect(json?.contains("\"\(key)\"") == true, "provenance_json lacks \(key)")
        }
        #expect(throws: StorageError.self) { try messages.finish("missing", status: .done) }
    }

    @Test func draftsAndFeedback() throws {
        let f = try TreeFixtures.treeBasic()
        let drafts = DraftRepository(f.database)
        try drafts.save(chatID: DraftRecord.newChatKey, text: "hello", attachmentsJSON: "[]")
        try drafts.adoptNewDraft(into: f.chatID)
        #expect(try drafts.draft(chatID: DraftRecord.newChatKey) == nil)
        #expect(try drafts.draft(chatID: f.chatID)?.text == "hello")
        try drafts.save(chatID: f.chatID, text: "")
        #expect(try drafts.draft(chatID: f.chatID) == nil)
        try drafts.save(chatID: f.chatID, text: "again")
        try drafts.delete(chatID: f.chatID)
        #expect(try drafts.draft(chatID: f.chatID) == nil)
        try drafts.adoptNewDraft(into: f.chatID)  // nothing to adopt

        let feedback = FeedbackRepository(f.database)
        try feedback.setRating(f.ids[1], .liked)
        #expect(try feedback.rating(f.ids[1]) == .liked)
        try feedback.setRating(f.ids[1], .disliked, note: "wrong")
        #expect(try feedback.rating(f.ids[1]) == .disliked)
        try feedback.flag(f.ids[1], .report, note: "r")
        #expect(Set(try feedback.feedback(f.ids[1]).map(\.kind)) == [.disliked, .report])
        try feedback.setRating(f.ids[3], .liked)
        #expect(try feedback.likedMessageIDs() == [f.ids[3]])
        try feedback.setRating(f.ids[1], nil)
        #expect(try feedback.rating(f.ids[1]) == nil)

        // A chat's draft goes with the chat.
        try drafts.save(chatID: f.chatID, text: "bye")
        try ChatRepository(f.database).delete(f.chatID)
        #expect(try drafts.draft(chatID: f.chatID) == nil)
        #expect(try feedback.feedback(f.ids[3]).isEmpty)
    }

