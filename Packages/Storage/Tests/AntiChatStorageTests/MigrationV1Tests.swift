    @Test func supportRecordsRoundTrip() throws {
        let f = try TreeFixtures.treeBasic()
        let t = Date(timeIntervalSince1970: 1_800_000_000.5)  // exactly representable both ways
        try f.database.write { (db: Database) throws in
            let blob = FileBlobRecord(sha256: String(repeating: "a", count: 64), size: 10, path: "Media/2026/a.png",
                                      createdAt: t, origin: .generated)
            try blob.insert(db)
            let attachment = AttachmentRecord(messageID: f.ids[0], blobID: blob.id, displayName: "a.png",
                                              uti: "public.png", pages: 1, createdAt: t)
            try attachment.insert(db)
            let job = MediaJobRecord(chatID: f.chatID, messageID: f.ids[1], kind: "image", specJSON: "{}", createdAt: t)
            try job.insert(db)
            let download = DownloadRecord(fileSHA256: blob.sha256, url: "https://huggingface.co/x", bytesTotal: 100,
                                          createdAt: t)
            try download.insert(db)
            #expect(try FileBlobRecord.fetchOne(db, key: blob.id) == blob)
            #expect(try AttachmentRecord.fetchOne(db, key: attachment.id) == attachment)
            #expect(try MediaJobRecord.fetchOne(db, key: job.id) == job)
            #expect(try DownloadRecord.fetchOne(db, key: download.id) == download)
            #expect(try LocalCounterRecord.increment("child_safety_blocks", in: db) == 1)
            #expect(try LocalCounterRecord.increment("child_safety_blocks", by: 2, in: db) == 3)
            // A blob still referenced by an attachment cannot be deleted.
            #expect(throws: DatabaseError.self) { try FileBlobRecord.deleteOne(db, key: blob.id) }
        }
        // The attachment follows its message into a branch copy.
        let copy = try MessageTree(f.database).branchCopy(upTo: f.ids[1], title: "b")
        let copied = try f.database.read { (db: Database) throws in
            try Int.fetchOne(db, sql: """
                SELECT COUNT(*) FROM attachment a JOIN message m ON m.id = a.message_id WHERE m.chat_id = ?
                """, arguments: [copy])
        }
        #expect(copied == 1)
    }

    /// `tools/fixtures/gen-chats.py` writes a v1 database that `AppDatabase` opens without migrating or erasing,
    /// with the requested shape, the `zebracorn` token in exactly one body and valid trees.
    @Test func genChatsWritesAValidV1Database() throws {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("antichat-genchats-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        let out = dir.appendingPathComponent("big.sqlite")
        let process = Process()
        process.executableURL = URL(fileURLWithPath: "/usr/bin/env")
        process.arguments = ["python3", "-I", repoRoot.appendingPathComponent("tools/fixtures/gen-chats.py").path,
                             "--chats", "200", "--long", "1:300", "--turns", "50", "--out", out.path]
        process.standardOutput = FileHandle.nullDevice
        try process.run()
        process.waitUntilExit()
        #expect(process.terminationStatus == 0)
        let database = try AppDatabase.onDisk(at: out)
        try database.read { (db: Database) throws in
            #expect(try Int.fetchOne(db, sql: "SELECT COUNT(*) FROM chat") == 200)
            #expect(try Int.fetchOne(db, sql: "SELECT MAX(n) FROM (SELECT COUNT(*) AS n FROM message GROUP BY chat_id)")
                ?? 0 >= 300)
            #expect(try Int.fetchOne(db, sql: "SELECT COUNT(*) FROM message_part WHERE body LIKE '%zebracorn%'") == 1)
            #expect(try TreeInvariants.violations(db) == [])
            #expect(try schemaDump(db) == String(contentsOf: schemaSnapshotURL, encoding: .utf8))
        }
        #expect(try MessageRepository(database).search("zebracorn").count == 1)
        #expect(try database.repairFullTextIfNeeded() == false)
    }
