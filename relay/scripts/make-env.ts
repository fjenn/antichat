// Writes relay/.env.local (gitignored) for `make relay-dev`: the stub Composio key (→ 503 relay.notConfigured)
// and a random 32-byte INSTALL_ID_HMAC_SECRET. Never overwrites an existing file unless --force.
// Usage: npx tsx scripts/make-env.ts [--force] [--mock]   (--mock: test-mock-key + local mock Composio instead)
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const dir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(dir, ".env.local");
if (existsSync(out) && !process.argv.includes("--force")) {
  process.stdout.write(`${out} exists (use --force to replace)\n`);
  process.exit(0);
}
const mock = process.argv.includes("--mock");
const lines = [
  "# Generated by scripts/make-env.ts. Local only (gitignored). Variables: architecture.md §8.3.",
  `COMPOSIO_API_KEY=${mock ? "test-mock-key" : "dev-not-a-key"}`,
  `INSTALL_ID_HMAC_SECRET=${randomBytes(32).toString("hex")}`,
  "RELAY_ALLOWED_TOOLKITS=*",
  "RELAY_MIN_CLIENT_VERSION=0",
  "RELAY_GLOBAL_DAILY_CAP=10000",
  "RELAY_DISABLED=0",
  ...(mock ? ["RELAY_LOCAL_MOCK=1", "COMPOSIO_ALLOW_INSECURE_HTTP=1"] : []),
];
writeFileSync(out, lines.join("\n") + "\n", { mode: 0o600 });
process.stdout.write(`wrote ${out}\n`);
