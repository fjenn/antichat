#!/usr/bin/env python3
"""PinnedKeys.swift generator + release-keys guard (M10.T04 steps 1–3; R-305 AC2; ci-release §6.1). `python3 -I`.

Reads Config/Keys.dev.plist and Config/Keys.release.plist (public keys only) and writes
Packages/Platform/Sources/AntiChatPlatform/Catalog/PinnedKeys.swift with both channels:
  #if ANTICHAT_RELEASE_KEYS  → the release catalog keys A/B, or `#error` when any of them (or the release Sparkle
                               key) is a test key listed in catalog/test-keys/FINGERPRINTS (Swift cannot compare
                               values at compile time, so the generator decides);
  #else                      → the dev keys (Debug builds, adhoc/dev RCs with ANTICHAT_ALLOW_DEV_KEYS=1).
build-release.sh compiles with ANTICHAT_RELEASE_KEYS unless ANTICHAT_ALLOW_DEV_KEYS=1, and stamps SUPublicEDKey
from the same plist into the built app.

  --check            exit 1 when PinnedKeys.swift differs from what the plists produce (make audit)
  --release-ready    exit 1 (with the reason) when the release plist still holds test keys (build-release preflight)
  --sparkle-key CH   print the Sparkle public key of channel dev|release
  --root DIR         another tree (tests: a fork's Config/Keys.*.plist)
"""
from __future__ import annotations

import argparse
import base64
import plistlib
import sys
from pathlib import Path

OUT = "Packages/Platform/Sources/AntiChatPlatform/Catalog/PinnedKeys.swift"
KEYS = ("SparklePublicEDKey", "CatalogPublicKeyA", "CatalogPublicKeyB")


def load(root: Path, channel: str) -> dict:
    d = plistlib.loads((root / f"Config/Keys.{channel}.plist").read_bytes())
    for k in KEYS:
        v = d.get(k, "")
        try:
            ok = len(base64.b64decode(v, validate=True)) == 32
        except ValueError:
            ok = False
        if not ok:
            raise SystemExit(f"Config/Keys.{channel}.plist: {k} is not a base64 32-byte Ed25519 public key")
    return d


def test_fingerprints(root: Path) -> dict[str, str]:
    f = root / "catalog/test-keys/FINGERPRINTS"
    out = {}
    for line in f.read_text().splitlines() if f.exists() else []:
        if line.strip() and not line.startswith("#"):
            key, _, name = line.partition("\t")
            out[key.strip()] = name.strip()
    return out


def release_problems(root: Path) -> list[str]:
    rel, tests = load(root, "release"), test_fingerprints(root)
    probs = [f"{k} is the test key {tests[rel[k]]}" for k in KEYS if rel[k] in tests]
    if len({rel[k] for k in KEYS}) < 3:
        probs.append("the Sparkle key and catalog keys A/B must be three different keys")
    return probs


def render(root: Path) -> str:
    dev, rel = load(root, "dev"), load(root, "release")
    probs = release_problems(root)
    guard = (f'    #error("PinnedKeys: Config/Keys.release.plist still holds test keys ({"; ".join(probs)}); '
             f'key ceremony: tools/release/KEYS.md")\n') if probs else ""
    return f"""// GENERATED by tools/release/gen-keys-swift.py from Config/Keys.{{dev,release}}.plist — do not edit (M10.T04).
// M2.T04/T05 (R-220 AC1, NFR-SEC7; ci-release §6.1, adr-distribution §4): the two pinned Ed25519 public keys a
// catalog may be signed with (A or B, for rotation). Release-keys builds (ANTICHAT_RELEASE_KEYS, set by
// tools/release/build-release.sh) pin Config/Keys.release.plist and stop here while it holds test keys.
import Foundation

public enum PinnedKeys {{
    /// The test public keys: a release must never ship them.
    static let testKeyA = "{dev["CatalogPublicKeyA"]}"
    static let testKeyB = "{dev["CatalogPublicKeyB"]}"

    #if ANTICHAT_RELEASE_KEYS
{guard}    /// Base64 raw Curve25519 signing public keys, A first (Config/Keys.release.plist).
    public static let keys: [String] = ["{rel["CatalogPublicKeyA"]}", "{rel["CatalogPublicKeyB"]}"]
    public static let isReleaseChannel = true
    #else
    /// Base64 raw Curve25519 signing public keys, A first (Config/Keys.dev.plist).
    public static let keys: [String] = [testKeyA, testKeyB]
    public static let isReleaseChannel = false
    #endif
}}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--release-ready", action="store_true")
    ap.add_argument("--sparkle-key", choices=["dev", "release"])
    a = ap.parse_args()
    root = Path(a.root)
    if a.sparkle_key:
        print(load(root, a.sparkle_key)["SparklePublicEDKey"])
        return 0
    if a.release_ready:
        probs = release_problems(root)
        for p in probs:
            print(f"gen-keys-swift: release keys not ready: {p}")
        return 1 if probs else 0
    text, out = render(root), root / OUT
    if a.check:
        same = out.exists() and out.read_text() == text
        print(f"gen-keys-swift: {'ok' if same else f'{OUT} is stale (run python3 -I tools/release/gen-keys-swift.py)'}")
        return 0 if same else 1
    out.write_text(text)
    print(f"gen-keys-swift: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
