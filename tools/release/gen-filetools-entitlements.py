#!/usr/bin/env python3
"""Writes App/FileToolsHelper/FileTools[Net][-Debug].entitlements (M6.T17, A-M6-11; A-M6-T18b closed in M6.T19).

Run: python3 -I tools/release/gen-filetools-entitlements.py [--check]
--check exits 1 when a committed file differs from what this script writes (make audit / FileToolsJailTests rely on
the four files staying identical apart from the network key and the Dev Runtimes root), and when a File tools slot
bundle (A-M6-T21a (a): FileToolsProtocol.maxSlots per variant, ids app.antichat.AntiChat.FileTools[.Net].slot<k>) is
missing from project.yml with exactly its id and its variant's entitlements, or from tools/release/sign.sh's
entitlement map. Every slot of a variant signs with the SAME file: the same deny-only rules in every container.

The temporary-exception.sbpl rules are purely SUBTRACTIVE: they are appended to the App Sandbox profile (last match
wins) and only deny. They remove the base profile's own home-folder read allowances (~/Library/Keychains,
~/Library/Spelling, ~/Library/Fonts, Input Methods, Dictionaries, ...) that no entitlement switches off, so the
service and the interpreter it spawns (app-sandbox + inherit) can read nothing under /Users except their own
container, the service's own .xpc bundle and the Runtimes root(s), and write nothing under /Users but the container, and nothing under /Volumes or the keychain folders.
A-M6-T21a (a): inside its own container a slot writes ONLY the scratch folder (the jails, wiped when a lease moves),
and nothing in the per-bundle darwin user/temp/cache folders, so nothing a chat's code writes can outlive the lease.
"""
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
ROOT = REPO / "App" / "FileToolsHelper"
RUNTIMES = "/Library/Application Support/AntiChat/Runtimes"
DEV_RUNTIMES = "/Library/Application Support/AntiChat-Dev/Runtimes"


def render(net: bool, debug: bool) -> str:
    roots = [RUNTIMES] + ([DEV_RUNTIMES] if debug else [])
    keep = " ".join(f'(require-not (subpath (string-append (param "_HOME") "{r}")))' for r in roots)
    users = '(require-any (subpath "/Users") (subpath "/System/Volumes/Data/Users") (subpath (param "_HOME")))'
    rules = [
        # reads: own container, own (signed, read-only) .xpc bundle — Bundle.main needs its Info.plist — and the Runtimes
        f'(deny file-read* (require-all {users} (require-not (subpath (param "application_container"))) '
        f'(require-not (subpath (param "application_bundle"))) {keep}))',
        # writes: own container only
        f'(deny file-write* (require-all {users} (require-not (subpath (param "application_container")))))',
        # ... and in it only the scratch folder; never the per-bundle darwin folders (A-M6-T21a (a): a lease wipe of
        # the scratch folder then leaves nothing of the previous chat in the slot)
        # (the param names the container's Data folder, the service's home; the "/Data/scratch" spelling covers a
        # container-root value too; FileToolsJailTests proves <container root>/scratch is not writable)
        '(deny file-write* (require-all (subpath (param "application_container")) '
        '(require-not (subpath (string-append (param "application_container") "/scratch"))) '
        '(require-not (subpath (string-append (param "application_container") "/Data/scratch")))))',
        '(deny file-write* (subpath (param "application_darwin_user_dir")) (subpath (param "application_darwin_temp_dir")) '
        '(subpath (param "application_darwin_cache_dir")))',
        '(deny file-read* file-write* (subpath "/Volumes") (subpath "/Library/Keychains") '
        '(subpath "/System/Volumes/Data/Library/Keychains"))',
    ]
    name = "FileTools" + ("Net" if net else "") + ("-Debug" if debug else "")
    dev = " (Debug also reads the AntiChat-Dev dev container's)" if debug else ""
    netline = ('Net variant: network.client (used only when "Allow network for code" is on).' if net
               else "No network entitlement at all: no network.client, no network.server (NFR-SEC3).")
    out = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
        f"<!-- {name}.entitlements (M6.T17; A-M6-11; A-M6-T18b). GENERATED by tools/release/gen-filetools-entitlements.py.",
        f"     App Sandbox on; the only file access outside the service's own container is READ-ONLY to the installed runtime{dev}.",
        f"     {netline}",
        "     temporary-exception.sbpl: subtractive deny rules only (see the generator's docstring). -->",
        '<plist version="1.0">', "<dict>",
        "\t<key>com.apple.security.app-sandbox</key>", "\t<true/>",
        "\t<key>com.apple.security.temporary-exception.files.home-relative-path.read-only</key>", "\t<array>",
        *[f"\t\t<string>{r}/</string>" for r in roots], "\t</array>",
    ]
    if net:
        out += ["\t<key>com.apple.security.network.client</key>", "\t<true/>"]
    out += ["\t<key>com.apple.security.temporary-exception.sbpl</key>", "\t<array>",
            *[f"\t\t<string>{r}</string>" for r in rules], "\t</array>", "</dict>", "</plist>", ""]
    return "\n".join(out)


def max_slots() -> int:
    src = (REPO / "Packages/EngineProtocol/Sources/AntiChatEngineProtocol/FileTools/FileToolsMessages.swift").read_text()
    return int(re.search(r"static let maxSlots = (\d+)", src).group(1))


def slot_bundles() -> list[tuple[str, str, str]]:
    """(target / bundle name, bundle id, entitlements base name) of every slot service (A-M6-T21a (a))."""
    out = []
    for v, vid in (("", ""), ("Net", ".Net")):
        for k in range(1, max_slots() + 1):
            out.append((f"AntiChatFileTools{v}Slot{k}", f"app.antichat.AntiChat.FileTools{vid}.slot{k}", f"FileTools{v}"))
    return out


def check_slots() -> list[str]:
    bad = []
    proj = (REPO / "project.yml").read_text()
    sign = (REPO / "tools/release/sign.sh").read_text()
    for name, bid, ents in slot_bundles():
        m = re.search(rf"^  {name}:\n    templates: \[FileToolsSlot\]\n    templateAttributes:\n((?:      .*\n)+)", proj, re.M)
        if not m:
            bad.append(f"project.yml: slot target {name} missing")
            continue
        attrs = dict(re.findall(r"      (\w+): (\S+)", m.group(1)))
        if attrs.get("bundleID") != bid or attrs.get("entitlements") != ents or attrs.get("productName") != name:
            bad.append(f"project.yml: {name} must be {bid} with {ents}.entitlements, got {attrs}")
        if not re.search(rf"- target: {name}\n        embed: true", proj):
            bad.append(f"project.yml: {name} is not embedded in the app")
        if f"XPCServices/{name}.xpc" not in proj:
            bad.append(f"project.yml: the seal phase does not re-sign {name}")
        if not re.search(rf"Contents/XPCServices/AntiChatFileTools{ents[len('FileTools'):]}Slot\*?\.xpc\) echo \"\$repository_root/App/FileToolsHelper/{ents}\.entitlements\"", sign) \
                and not re.search(rf"Contents/XPCServices/{name}\.xpc\) echo \"\$repository_root/App/FileToolsHelper/{ents}\.entitlements\"", sign):
            bad.append(f"tools/release/sign.sh: no entitlements mapping for {name}.xpc ({ents}.entitlements)")
    extra = set(re.findall(r"^  (AntiChatFileTools\w*):", proj, re.M)) - {n for n, _, _ in slot_bundles()}
    for e in sorted(extra):
        bad.append(f"project.yml: {e} is a File tools target outside the slot set")
    return bad


def main() -> int:
    check = "--check" in sys.argv[1:]
    bad = 0
    if check:
        for b in check_slots():
            print(f"gen-filetools-entitlements: {b}", file=sys.stderr)
            bad = 1
    for net in (False, True):
        for debug in (False, True):
            path = ROOT / ("FileTools" + ("Net" if net else "") + ("-Debug" if debug else "") + ".entitlements")
            text = render(net, debug)
            if check:
                if not path.exists() or path.read_text() != text:
                    print(f"gen-filetools-entitlements: {path.name} is stale", file=sys.stderr)
                    bad = 1
            else:
                path.write_text(text)
    return bad


if __name__ == "__main__":
    sys.exit(main())
