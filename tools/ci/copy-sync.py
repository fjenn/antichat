#!/usr/bin/env python3
"""Copy-key sync (architecture §11 rule 6, copy-deck.md header; M1.T02). Run with `python3 -I`.

Checks, each failing with `file:line: …`:
  1. every key used in code exists in docs/research/10-architecture/design-system/copy-deck.md. Code keys =
     `userMessageKey: "<key>"`, `LocalizedStringResource("<key>")`, `String(localized: "<key>")`,
     `Text(LocalizedStringKey("<key>"))`, `CopyKey("<key>")` and `.copy("<key>")` in tracked Swift under App/ and
     Packages/ (vendored code excluded);
  2. when App/AntiChat/Localizable.xcstrings exists (generated by M1.T03): it holds exactly the copy-deck keys
     (missing or stale keys both fail).
The reverse direction "copy-deck key unused by code" is reported as a count only: the deck carries the keys of
later milestones (copy-deck.md is the source of truth, M1.T03 generates the catalog from it).
Copy-deck keys = the backticked dotted ids in the first column of each table row; a `/ .suffix` shorthand
(`onb.pack.chat.name` / `.verb`) expands against the previous key's stem.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from audit_common import ROOT, repo_files  # noqa: E402

DECK = "docs/research/10-architecture/design-system/copy-deck.md"
XCSTRINGS = "App/AntiChat/Localizable.xcstrings"
KEY = r"[a-z][A-Za-z0-9]*(?:\.[A-Za-z0-9{}]+)+"
CODE_RE = re.compile(
    r'(?:userMessageKey:\s*|LocalizedStringResource\(\s*|String\(localized:\s*|LocalizedStringKey\(\s*|'
    r'CopyKey\(\s*|\.copy\(\s*)"(' + KEY + r')"')


def deck_keys(path: Path) -> dict[str, int]:
    keys: dict[str, int] = {}
    for i, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.startswith("|"):
            continue
        cell = line.split("|")[1]
        prev = None
        for tok in re.findall(r"`([^`]+)`", cell):
            if tok.startswith(".") and prev:
                k = prev.rsplit(".", 1)[0] + tok
            elif re.fullmatch(KEY, tok):
                k = tok
            else:
                continue
            keys.setdefault(k, i)
            prev = k
    return keys


def code_keys(root: Path) -> list[tuple[str, int, str]]:
    out = []
    for f in repo_files(root, (".swift",)):
        r = str(f.relative_to(root))
        if not r.startswith(("App/", "Packages/")) or r.startswith("Packages/ChildSafetyCheck/.build"):
            continue
        for i, line in enumerate(f.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for m in CODE_RE.finditer(line.split("//", 1)[0]):
                out.append((r, i, m.group(1)))
    return out


def check(root: Path) -> tuple[list[str], dict]:
    errs: list[str] = []
    deck = deck_keys(root / DECK)
    used = code_keys(root)
    for r, i, k in used:
        if k not in deck:
            errs.append(f"{r}:{i}: copy key '{k}' is not in {DECK}")
    xc = root / XCSTRINGS
    xc_state = "absent (generated by M1.T03)"
    if xc.exists():
        strings = json.loads(xc.read_text(encoding="utf-8")).get("strings", {})
        for k in sorted(set(deck) - set(strings)):
            errs.append(f"{XCSTRINGS}: missing copy-deck key '{k}' ({DECK}:{deck[k]})")
        for k in sorted(set(strings) - set(deck)):
            errs.append(f"{XCSTRINGS}: key '{k}' is not in {DECK}")
        xc_state = f"{len(strings)} keys"
    stats = {"deck": len(deck), "code_refs": len(used), "code_keys": len({k for _, _, k in used}),
             "deck_unused_by_code": len(set(deck) - {k for _, _, k in used}), "xcstrings": xc_state}
    return errs, stats


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(ROOT))
    a = ap.parse_args()
    errs, st = check(Path(a.root).resolve())
    for e in errs:
        print(e)
    print(f"copy-sync: {'FAIL ' + str(len(errs)) if errs else 'ok'} {json.dumps(st)}")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
