#!/usr/bin/env python3
"""tools/ci/antichat-paths.txt from DataPaths.swift (M8.T10 DoD; NFR-D7). Run with `python3 -I`.

Every documented location in `Packages/Platform/Sources/AntiChatPlatform/Storage/DataPaths.swift` carries a trailing
`// path: <path>` comment; this writes them, one per line, in source order (`~` = the home folder, `$TMPDIR` = the
temp dir, `<…>` = a location only known at run time). `--check` fails (exit 1) when the file differs, so the list the
zero-files test reads can never drift from the code.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = "Packages/Platform/Sources/AntiChatPlatform/Storage/DataPaths.swift"
OUT = "tools/ci/antichat-paths.txt"
HEADER = "# Generated by tools/ci/gen-paths.py from DataPaths.swift — do not edit (gen-paths.py --check in make audit).\n"


def render(root: Path) -> str:
    lines = re.findall(r"//\s*path:\s*([~$<].+?)\s*$", (root / SRC).read_text(), flags=re.M)
    if not lines:
        raise SystemExit(f"{SRC}: no `// path:` lines")
    return HEADER + "".join(f"{p}\n" for p in lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(ROOT))
    a = ap.parse_args()
    root = Path(a.root)
    want = render(root)
    out = root / OUT
    if a.check:
        have = out.read_text() if out.exists() else ""
        if have != want:
            print(f"{OUT}: out of date with {SRC} (run python3 -I tools/ci/gen-paths.py)", file=sys.stderr)
            return 1
        print(f"gen-paths: {OUT} matches ({want.count(chr(10)) - 1} paths)")
        return 0
    out.write_text(want)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
