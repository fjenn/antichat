#!/usr/bin/env python3
"""Compile catalog/dev.yaml → catalog/dev-catalog.json (docs/prd/M1.md convention 4; M1.T02).

Run: tools/.venv/bin/python -I tools/dev/gen-dev-catalog.py [--check]   (needs PyYAML from tools/pyproject.toml)

Output = the hf-fetch manifest shape (`sets` → flat key lists, `models` → [{repo: "<repo>@<sha>", include}])
plus `catalog` (the per-key metadata: slot, engine, size_gb, context, smaller). Set members may name other
sets (expanded in order, de-duplicated). `catalog_keys` are product catalog ids (catalog/models.yaml) the dev sets
install under the same id the app uses (repo@commit + files from there). Validation: 40-hex commits, unique keys, `smaller` names a chat key
of the same engine family's slot, no cycles, every set member resolves. --check fails if the JSON is stale.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "catalog/dev.yaml")
OUT = os.path.join(ROOT, "catalog/dev-catalog.json")
M0 = os.path.join(ROOT, "tools/dev/models-m0.json")
PRODUCT = os.path.join(ROOT, "catalog/models.yaml")
REQ = ("key", "slot", "engine", "repo", "commit", "files", "size_gb", "context", "smaller")


def die(msg: str) -> None:
    print(f"gen-dev-catalog: {msg}", file=sys.stderr)
    sys.exit(1)


def build() -> dict:
    try:
        import yaml  # type: ignore
    except ImportError:
        die("PyYAML missing; run with tools/.venv/bin/python (bootstrap step 9)")
    with open(SRC, encoding="utf-8") as f:
        y = yaml.safe_load(f)
    with open(M0, encoding="utf-8") as f:
        m0 = json.load(f)

    catalog: dict[str, dict] = {}
    models: dict[str, list] = {}
    for m in y["models"]:
        missing = [k for k in REQ if k not in m]
        if missing:
            die(f"{m.get('key')}: missing {missing}")
        k = m["key"]
        if k in catalog:
            die(f"duplicate key {k}")
        if m["slot"] not in ("chat", "evil") or m["engine"] not in ("mlx", "llama"):
            die(f"{k}: bad slot/engine")
        if not re.fullmatch(r"[0-9a-f]{40}", m["commit"]):
            die(f"{k}: commit must be a full 40-hex sha")
        catalog[k] = {f: m[f] for f in REQ if f != "key"}
        entry: dict = {"repo": f"{m['repo']}@{m['commit']}"}
        if m["files"] != ["*"]:
            entry["include"] = list(m["files"])
        models[k] = [entry]
    for k, m in catalog.items():
        s = m["smaller"]
        if s is None:
            continue
        if s not in catalog or catalog[s]["slot"] != m["slot"]:
            die(f"{k}: smaller={s} is not a {m['slot']} key")
        seen, cur = {k}, s
        while cur is not None:
            if cur in seen:
                die(f"{k}: smaller chain has a cycle")
            seen.add(cur)
            cur = catalog[cur]["smaller"]
    for k in y.get("m0_keys", []):
        if k not in m0["models"]:
            die(f"m0 key {k} not in tools/dev/models-m0.json")
        if k in models:
            die(f"m0 key {k} clashes with a dev key")
        models[k] = m0["models"][k]

    if y.get("catalog_keys"):
        with open(PRODUCT, encoding="utf-8") as f:
            product = {m["key"]: m for m in yaml.safe_load(f)["models"]}
        for k in y["catalog_keys"]:
            if k not in product:
                die(f"catalog key {k} not in catalog/models.yaml")
            if k in models:
                die(f"catalog key {k} clashes with a dev or m0 key")
            m = product[k]
            entry = {"repo": f"{m['repo']}@{m['commit']}"}
            if m.get("files", ["*"]) != ["*"]:
                entry["include"] = list(m["files"])
            models[k] = [entry]

    raw = y["sets"]

    def expand(name: str, stack: tuple[str, ...]) -> list[str]:
        if name in stack:
            die(f"set cycle {' → '.join(stack + (name,))}")
        out: list[str] = []
        for member in raw[name]:
            items = expand(member, stack + (name,)) if member in raw else [member]
            for it in items:
                if it not in models:
                    die(f"set {name}: unknown key {it}")
                if it not in out:
                    out.append(it)
        return out

    sets = {n: expand(n, ()) for n in raw}
    return {
        "_doc": "GENERATED by tools/dev/gen-dev-catalog.py from catalog/dev.yaml; do not edit.",
        "version": y["version"],
        "sets": sets,
        "models": models,
        "catalog": catalog,
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = json.dumps(build(), indent=1, ensure_ascii=False) + "\n"
    if a.check:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            die("catalog/dev-catalog.json is stale; run make dev-catalog")
        return 0
    tmp = OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, OUT)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(text)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
