# ---------------------------------------------------------------- spacing, layout, radius, motion

def spacing(secs) -> tuple[list[tuple[str, float]], list[tuple[str, str, str]]]:
    space, layout = [], []
    for line_cells in table_rows(secs.get("3", [])):
        cells = line_cells
        if len(cells) == 4 and cells[0].startswith("`space."):
            for i in (0, 2):
                k = keys_in(cells[i])
                if k:
                    space.append((k[0], float(cells[i + 1])))
        elif len(cells) == 2 and cells[0].startswith("`layout."):
            k = keys_in(cells[0])[0]
            layout.append((k, cells[1], ""))
    space.sort(key=lambda kv: int(kv[0].rsplit(".", 1)[1]))
    return space, layout


def layout_consts(layout) -> list[tuple[str, str, str, str]]:
    """→ (swift name, type, value expr, doc)."""
    out = []
    for key, val, _ in layout:
        base = camel(key.removeprefix("layout."))
        v = val.replace("×", "x")
        size = re.match(r"^(\d+)\s*x\s*(\d+)", v)
        if size:
            out.append((base, "CGSize", f"CGSize(width: {size.group(1)}, height: {size.group(2)})", val))
        else:
            pct = re.match(r"^(\d+)%", v)
            num = re.match(r"^(\d+)", v)
            if pct:
                out.append((base + "Fraction", "CGFloat", f"{int(pct.group(1)) / 100}", val))
                mn = re.search(r"min (\d+)", v)
                if mn:
                    out.append((base + "Min", "CGFloat", mn.group(1), val))
            elif num:
                out.append((base, "CGFloat", num.group(1), val))
                for word, suffix in (("min", "Min"), ("max", "Max")):
                    m = re.search(rf"\b{word} (\d+)(%?)", v)
                    if m:
                        if m.group(2):
                            out.append((base + suffix + "Fraction", "CGFloat", f"{int(m.group(1)) / 100}", val))
                        else:
                            out.append((base + suffix, "CGFloat", m.group(1), val))
        dflt = re.search(r"default (\d+)\s*x\s*(\d+)", v)
        if dflt:
            out.append((base.removesuffix("Min") + "Default", "CGSize",
                        f"CGSize(width: {dflt.group(1)}, height: {dflt.group(2)})", val))
        gap = re.search(r"gap (\d+)", v)
        if gap:
            out.append((base + "Gap", "CGFloat", gap.group(1), val))
        parts = re.search(r"; (\d+) between parts", v)
        if parts:
            out.append((base + "Parts", "CGFloat", parts.group(1), val))
        cw = re.search(r"content max width (\d+)", v)
        if cw:
            out.append((base + "ContentMaxWidth", "CGFloat", cw.group(1), val))
    return out


def gen_spacing(space, layout) -> str:
    lines = [HEADER, "import CoreGraphics", "", "/// tokens.md §3: the 4-pt grid.", "public enum Spacing {"]
    for k, v in space:
        lines.append(f"    /// `{k}`")
        lines.append(f"    public static let {camel(k)}: CGFloat = {v:g}")
    lines += ["}", "", "/// tokens.md §3 layout tokens (values in points).", "public enum Layout {"]
    for name, typ, expr, doc in layout_consts(layout):
        lines.append(f"    /// {doc}")
        lines.append(f"    public static let {name}: {typ} = {expr}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def radius(secs) -> tuple[list, list, list]:
    radii, strokes, shadows = [], [], []
    for cells in table_rows(secs.get("4", [])):
        k = keys_in(cells[0])
        if not k:
            continue
        k, v = k[0], cells[1]
        if k.startswith("radius."):
            radii.append((k, int(re.match(r"\d+", v).group(0)), cells[2]))
        elif k.startswith("stroke."):
            strokes.append((k, v, cells[2]))
        elif k.startswith("shadow."):
            m = re.match(r"y (\d+), blur (\d+), `#([0-9A-Fa-f]{8})`", v)
            if not m:
                raise GenError(f"§4 shadow {k}: {v!r}")
            shadows.append((k, int(m.group(1)), int(m.group(2)), m.group(3).upper(), cells[2]))
    return radii, strokes, shadows


def gen_radius(radii, strokes, shadows) -> str:
    lines = [HEADER, "import SwiftUI", "", "/// tokens.md §4 corner radii.", "public enum Radius {"]
    for k, v, use in radii:
        lines.append(f"    /// `{k}`: {use}")
        lines.append(f"    public static let {camel(k.removeprefix('radius.'))}: CGFloat = {v}")
    lines += ["}", "", "/// tokens.md §4 strokes. `hairlinePixels` is in device pixels (1 px = 0.5 pt on Retina).",
              "public enum Stroke {"]
    for k, v, use in strokes:
        base = camel(k.removeprefix("stroke."))
        if "px" in v:
            lines.append(f"    /// `{k}`: {v}")
            lines.append(f"    public static let {base}Pixels: CGFloat = {re.match(r'[0-9.]+', v).group(0)}")
            lines.append(f"    /// `{k}` in points for a display scale.")
            lines.append(f"    public static func {base}(scale: CGFloat) -> CGFloat {{ {base}Pixels / max(scale, 1) }}")
        else:
            lines.append(f"    /// `{k}`: {v}")
            lines.append(f"    public static let {base}: CGFloat = {re.match(r'[0-9.]+', v).group(0)}")
            off = re.search(r"offset (\d+)", v)
            if off:
                lines.append(f"    public static let {base}Offset: CGFloat = {off.group(1)}")
    lines += ["}", "", "/// tokens.md §4 elevation.", "public struct ShadowToken: Sendable, Hashable {",
              "    public let y: CGFloat", "    public let blur: CGFloat", "    /// 0xRRGGBBAA", "    public let rgba: UInt32",
              "    public var color: Color { Color(tokenHex: rgba) }", "}", "", "public extension ShadowToken {"]
    for k, y, blur, rgba, use in shadows:
        lines.append(f"    /// `{k}`: {use}")
        lines.append(f"    static let level{k.removeprefix('shadow.')} = ShadowToken(y: {y}, blur: {blur}, rgba: 0x{rgba})")
    lines.append("}")
    return "\n".join(lines) + "\n"


def motion(secs) -> list[dict]:
    out = []
    for cells in table_rows(secs.get("5", [])):
        k = keys_in(cells[0])
        if not k:
            continue
        dur, curve, rm = cells[1], cells[2], cells[4]
        each = re.search(r"(\d+) ms each", dur)  # motion.onboarding.stagger: "60 ms between elements, 400 ms each"
        ms = re.match(r"(\d+(?:\.\d+)?)\s*(ms|s)\b", f"{each.group(1)} ms" if each else dur)
        d = 0.0
        if ms:
            d = float(ms.group(1)) / (1000 if ms.group(2) == "ms" else 1)
        c = curve.lower()
        if ".smooth" in c:
            kind = "smooth"
        elif "easeinout" in c:
            kind = "easeInOut"
        elif "easeout" in c:
            kind = "easeOut"
        elif "linear" in c:
            kind = "linear"
        else:
            kind = "none"
        r = rm.lower()
        cf = re.search(r"cross-fade (\d+) ?ms|(\d+) ?ms cross-fade", r)
        if r == "same":
            reduce = "same"
        elif "opacity only" in r:
            reduce = "opacityOnly"
        elif cf:
            reduce = f"crossFade({int(cf.group(1) or cf.group(2)) / 1000})"
        else:
            reduce = "none"
        out.append({"name": k[0], "duration": d, "curve": kind, "reduce": reduce, "use": cells[3], "rmText": rm,
                    "durText": dur})
    return out


def gen_motion(ms: list[dict]) -> str:
    lines = [HEADER, "import Foundation", "", "/// tokens.md §5 motion tokens. Behaviour (Reduce Motion paths) lives in MotionPolicy.swift.",
             "public extension MotionToken {"]
    for m in ms:
        nm = camel(m["name"].removeprefix("motion."))
        lines.append(f"    /// `{m['name']}` {m['durText']}: {m['use']}. Reduce Motion: {m['rmText']}.")
        lines.append(f"    static let {nm} = MotionToken(name: \"{m['name']}\", duration: {m['duration']}, "
                     f"curve: .{m['curve']}, reduceMotion: .{m['reduce']})")
    lines.append("    static let all: [MotionToken] = [" + ", ".join(camel(m["name"].removeprefix("motion.")) for m in ms) + "]")
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- catalog (tests) + contrast pairs

def pairs(secs, toks) -> list[dict]:
    out = []
    for cells in table_rows(secs.get("7", [])):
        fg = keys_in(cells[0])
        bgs = [b.strip() for b in cells[1].replace("`", "").split(" over ")]
        if not fg:
            continue
        for n in fg + bgs:
            if n not in toks:
                raise GenError(f"§7 pair names unknown token {n}")
        out.append({"fg": fg[0], "bg": bgs, "min": float(cells[2]), "modes": cells[3], "where": cells[4]})
    return out


def gen_catalog(toks, prs, skipped) -> str:
    def lit(spec, key):
        v = resolved(spec, key)
        return f"0x{v[1:]}" if v else "nil"
    lines = [HEADER, "", "/// Raw token values for tests (DesignTokenContrastTests, asset-catalog parity). 0xRRGGBBAA.",
             "enum TokenCatalog {",
             "    struct ColorSpec: Sendable {",
             "        let name: String",
             "        let light: UInt32", "        let dark: UInt32",
             "        let highContrastLight: UInt32", "        let highContrastDark: UInt32",
             "        /// `sys:` token (asset holds the brand fallback, or no asset at all).",
             "        let system: String?", "        let hasAsset: Bool", "    }",
             "    struct ContrastPair: Sendable {",
             "        let foreground: String", "        /// Bottom-most last: `a over b` → [a, b].",
             "        let background: [String]", "        let minimum: Double", "        let lightOnly: Bool",
             "        let usage: String", "    }", "", "    static let colors: [ColorSpec] = ["]
    for name in sorted(toks):
        s = toks[name]
        if "gradient" in (s["light"] or {}):
            continue
        sysn = s["light"].get("sys") if isinstance(s["light"], dict) else None
        l, d = resolved(s, "light"), resolved(s, "dark")
        if l is None:  # sys token without a fallback (focus.ring): not a fixed colour
            lines.append(f"        ColorSpec(name: \"{name}\", light: 0, dark: 0, highContrastLight: 0, highContrastDark: 0, "
                         f"system: \"{sysn}\", hasAsset: false),")
            continue
        hl = s.get("hcLight") or l
        hd = s.get("hcDark") or d
        lines.append(f"        ColorSpec(name: \"{name}\", light: 0x{l[1:]}, dark: 0x{d[1:]}, highContrastLight: 0x{hl[1:]}, "
                     f"highContrastDark: 0x{hd[1:]}, system: {('\"' + sysn + '\"') if sysn else 'nil'}, hasAsset: true),")
    lines.append("    ]")
    lines.append("")
    lines.append("    static let contrastPairs: [ContrastPair] = [")
    for p in prs:
        bg = ", ".join(f"\"{b}\"" for b in p["bg"])
        lines.append(f"        ContrastPair(foreground: \"{p['fg']}\", background: [{bg}], minimum: {p['min']}, "
                     f"lightOnly: {'true' if p['modes'] == 'light' else 'false'}, usage: \"{swift_str(p['where'])}\"),")
    lines.append("    ]")
    lines.append("")
    lines.append("    /// tokens.md rows that are not a fixed colour value (kept visible, never dropped silently).")
    lines.append("    static let skipped: [String: String] = [")
    for n, why in skipped:
        lines.append(f"        \"{n}\": \"{swift_str(why)}\",")
    if not skipped:
        lines.append("        :")
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- main

def build() -> dict[Path, str]:
    text = SRC.read_text(encoding="utf-8")
    secs = sections(text)
    toks, skipped = colours(secs)
    for n, s in toks.items():
        for k in ("light", "dark"):
            if s[k] is None:
                raise GenError(f"colour token {n} has no {k} value")
    files: dict[Path, str] = {}
    files[TOK_DIR / "Color+Tokens.swift"] = gen_colour_swift(toks)
    rw = {m.group(1): int(m.group(2)) for m in re.finditer(r"(Narrow|Default|Wide) (\d+)", text)}
    files[TOK_DIR / "Typography.swift"] = gen_typography(typography(secs), rw)
    sp, lay = spacing(secs)
    files[TOK_DIR / "Spacing.swift"] = gen_spacing(sp, lay)
    files[TOK_DIR / "Radius.swift"] = gen_radius(*radius(secs))
    files[TOK_DIR / "Motion.swift"] = gen_motion(motion(secs))
    files[TOK_DIR / "TokenCatalog.swift"] = gen_catalog(toks, pairs(secs, toks), skipped)
    files[XCASSETS / "Contents.json"] = json.dumps({"info": {"author": "xcode", "version": 1}}, indent=2) + "\n"
    for n in sorted(toks):
        s = toks[n]
        if "gradient" in (s["light"] or {}) or resolved(s, "light") is None:
            continue
        files[XCASSETS / f"{n}.colorset/Contents.json"] = json.dumps(colorset(s), indent=2, sort_keys=True) + "\n"
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        files = build()
    except GenError as e:
        print(f"gen-tokens: {SRC.relative_to(ROOT)}: {e}", file=sys.stderr)
        return 1
    stale = [p for p in XCASSETS.glob("*.colorset") if p / "Contents.json" not in files] if XCASSETS.exists() else []
    if a.check:
        diff = [p for p, c in files.items() if not p.exists() or p.read_text(encoding="utf-8") != c] + stale
        for p in diff:
            print(f"gen-tokens: stale {p.relative_to(ROOT)}")
        print(f"gen-tokens --check: {'FAIL' if diff else 'ok'} ({len(files)} files)")
        return 1 if diff else 0
    for p in stale:
        for f in p.iterdir():
            f.unlink()
        p.rmdir()
    for p, c in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text(encoding="utf-8") != c:
            p.write_text(c, encoding="utf-8")
    n_col = sum(1 for p in files if p.parent.suffix == ".colorset")
    print(f"gen-tokens: ok ({len(files)} files, {n_col} colour sets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
