HEX = re.compile(r"#([0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?)\b")


class GenError(Exception):
    pass


# ---------------------------------------------------------------- markdown helpers

def sections(text: str) -> dict[str, list[str]]:
    """Map '1.1', '2', '7', … → lines of that (sub)section."""
    out: dict[str, list[str]] = {}
    cur = None
    for line in text.splitlines():
        m = re.match(r"^#{2,3}\s+(\d+(?:\.\d+)?)\.?\s", line)
        if m:
            cur = m.group(1)
            out[cur] = []
            continue
        if cur is not None:
            out[cur].append(line)
    return out


def table_rows(lines: list[str]) -> list[list[str]]:
    rows = []
    for line in lines:
        s = line.strip()
        if not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if all(re.fullmatch(r":?-{3,}:?", c) for c in cells):
            continue
        rows.append(cells)
    return rows[1:] if rows else []  # drop header


def keys_in(cell: str) -> list[str]:
    """`a.b` / `.c` / `a.d` → ['a.b', 'a.c', 'a.d'] (the copy-sync shorthand)."""
    out: list[str] = []
    for tok in re.findall(r"`([^`]+)`", cell):
        if tok.startswith(".") and out:
            out.append(out[-1].rsplit(".", 1)[0] + tok)
        elif re.fullmatch(r"[a-z][A-Za-z0-9]*(\.[A-Za-z0-9]+)*", tok):
            out.append(tok)
    return out


def swift_str(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def camel(name: str) -> str:
    parts = re.split(r"[.\-]", name)
    s = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return "`default`" if s == "default" else s


# ---------------------------------------------------------------- colour

def norm_hex(h: str, alpha_pct: float | None = None) -> str:
    h = h.upper()
    if len(h) == 6:
        h += "FF" if alpha_pct is None else f"{round(alpha_pct * 255 / 100):02X}"
    return "#" + h


def parse_value(cell: str) -> dict[str, str] | str | None:
    """A colour cell → '#RRGGBBAA' | {'sys': name, 'fallback'?: hex} | {'': base?, 'bg'|'fg'|'label'|'border': hex}."""
    cell = cell.strip()
    if cell in ("", "—", "-"):
        return None
    m = re.search(r"`sys:([A-Za-z]+)`", cell)
    if m:
        d = {"sys": m.group(1)}
        first = HEX.search(cell)
        if first:
            d["fallback"] = norm_hex(first.group(1))
        return d
    sub = list(re.finditer(r"\b(bg|fg|label|border)\s*`#([0-9A-Fa-f]{6,8})`", cell))
    fb = re.search(r"fallback\s*`#([0-9A-Fa-f]{6,8})`", cell)  # `.glassEffect(.regular)` …; fallback `#…`
    base = None
    if fb:
        base = norm_hex(fb.group(1))
    else:
        first = HEX.search(cell)
        if first and (not sub or first.start() < sub[0].start()):
            pct = re.search(re.escape(first.group(0)) + r"`?\s+at\s+(\d+)%", cell)
            base = norm_hex(first.group(1), float(pct.group(1)) if pct else None)
    if not sub:
        return base
    d = {k.group(1): norm_hex(k.group(2)) for k in sub}
    if base:
        d[""] = base
    return d


def colours(secs: dict[str, list[str]]) -> tuple[dict[str, dict], list[tuple[str, str]]]:
    toks: dict[str, dict] = {}
    skipped: list[tuple[str, str]] = []

    def put(name: str, light, dark, src: str):
        if name in toks:
            raise GenError(f"duplicate colour token {name}")
        toks[name] = {"light": light, "dark": dark, "src": src}

    for sec in ("1.1", "1.2", "1.3", "1.4", "1.5", "1.6"):
        for cells in table_rows(secs.get(sec, [])):
            if sec == "1.5":   # Pack | Token | Value (both modes) | …
                names, lv, dv = keys_in(cells[1]), cells[2], cells[2]
            elif sec == "1.6":  # Token | Value | Notes
                names, lv, dv = keys_in(cells[0]), cells[1], cells[1]
            else:               # Token | Light | Dark | …
                names, lv, dv = keys_in(cells[0]), cells[1], cells[2]
            if not names:
                continue
            if "gradient" in names[0]:
                stops = [norm_hex(h) for h in HEX.findall(dv)]
                put(names[0], {"gradient": stops}, {"gradient": stops}, sec)
                continue
            # multi-key rows: values split on ' / ' in the same order
            if len(names) > 1:
                lparts = [p.strip() for p in lv.split(" / ")]
                dparts = [p.strip() for p in dv.split(" / ")]
                if len(lparts) != len(names) or len(dparts) != len(names):
                    raise GenError(f"§{sec}: {len(names)} keys but values {lv!r} / {dv!r}")
                for n, l, d in zip(names, lparts, dparts):
                    put(n, parse_value(l), parse_value(d) if d != "same" else parse_value(l), sec)
                continue
            name = names[0]
            light = parse_value(lv)
            dark = parse_value(lv) if dv.strip() == "same" else parse_value(dv)
            if light is None and dark is None:
                why = "alias row (no value of its own)" if lv.strip() == "" else f"no colour value ({lv!r})"
                skipped.append((name, f"§{sec}: {why}"))
                continue
            if light is None:   # dark-context token (onboarding): same value in both appearances
                light = dark
            if isinstance(light, dict) and isinstance(dark, dict) and "sys" not in light and "sys" not in dark:
                for k in sorted(set(light) | set(dark)):
                    put(name + ("." + k if k else ""), light.get(k, dark.get(k)), dark.get(k, light.get(k)), sec)
                continue
            put(name, light, dark, sec)

    # §1.7 Increase Contrast overrides
    for cells in table_rows(secs.get("1.7", [])):
        names = keys_in(cells[0])
        if not names:
            continue
        n = names[0]
        if n not in toks:
            raise GenError(f"§1.7 override for unknown token {n}")
        toks[n]["hcLight"] = parse_value(cells[1])
        toks[n]["hcDark"] = parse_value(cells[2])
    return toks, skipped


def resolved(spec: dict, key: str) -> str | None:
    v = spec.get(key)
    if isinstance(v, dict):
        return v.get("fallback")
    return v


def colorset(spec: dict) -> dict:
    def comp(h: str) -> dict:
        h = h.lstrip("#")
        return {"color-space": "srgb", "components": {
            "red": "0x" + h[0:2], "green": "0x" + h[2:4], "blue": "0x" + h[4:6],
            "alpha": f"{int(h[6:8], 16) / 255:.3f}"}}
    l, d = resolved(spec, "light"), resolved(spec, "dark")
    hl, hd = spec.get("hcLight") or l, spec.get("hcDark") or d
    entries = [
        {"color": comp(l), "idiom": "universal"},
        {"appearances": [{"appearance": "luminosity", "value": "dark"}], "color": comp(d), "idiom": "universal"},
        {"appearances": [{"appearance": "contrast", "value": "high"}], "color": comp(hl), "idiom": "universal"},
        {"appearances": [{"appearance": "luminosity", "value": "dark"}, {"appearance": "contrast", "value": "high"}],
         "color": comp(hd), "idiom": "universal"},
    ]
    return {"colors": entries, "info": {"author": "xcode", "version": 1}}


def gen_colour_swift(toks: dict[str, dict]) -> str:
    out = [HEADER, "import SwiftUI", "import AppKit", "",
           "// One constant per tokens.md §1 colour token. `sys:` tokens are the macOS semantic colour itself, so",
           "// Increase Contrast, the accent colour and Reduce Transparency come from the OS (tokens.md header).",
           "// `accent` falls back to the AntiChat brand blue when the user's accent is Multicolor.",
           "public extension Color {"]
    ns = ["public extension NSColor {"]
    for name in sorted(toks):
        s = toks[name]
        if "gradient" in (s["light"] or {}):
            continue
        sw = camel(name)
        l = s["light"]
        if isinstance(l, dict) and "sys" in l:
            sysname = l["sys"]
            if "fallback" in l:
                out.append(f"    /// `{name}`: `sys:{sysname}`; brand fallback when the system accent is Multicolor.")
                out.append(f"    static var {sw}: Color {{ DesignBundle.usesSystemAccent ? Color(nsColor: .{sysname}) "
                           f": Color(\"{name}\", bundle: .module) }}")
                ns.append(f"    static var {sw}: NSColor {{ DesignBundle.usesSystemAccent ? .{sysname} "
                          f": NSColor(named: \"{name}\", bundle: .module)! }}")
            else:
                out.append(f"    /// `{name}`: `sys:{sysname}`.")
                out.append(f"    static var {sw}: Color {{ Color(nsColor: .{sysname}) }}")
                ns.append(f"    static var {sw}: NSColor {{ .{sysname} }}")
            continue
        out.append(f"    /// `{name}` (tokens.md §{s['src']}).")
        hl, hd = s.get("hcLight"), s.get("hcDark")
        if hl or hd:
            # M1.T23: Settings → Appearance → Increase contrast "Always on" forces the high-contrast value
            # (macOS cannot be asked for a high-contrast NSAppearance), so these tokens resolve through it.
            lv, dv = resolved(s, "light"), resolved(s, "dark")
            hx = lambda h: "0x" + h.lstrip("#").upper()
            hc = f"ContrastOverride.highContrast(\"{name}\", {hx(hl or lv)}, {hx(hd or dv)})"
            out.append(f"    static var {sw}: Color {{ ContrastOverride.isForced ? Color(nsColor: {hc}) "
                       f": Color(\"{name}\", bundle: .module) }}")
            ns.append(f"    static var {sw}: NSColor {{ ContrastOverride.isForced ? {hc} "
                      f": NSColor(named: \"{name}\", bundle: .module)! }}")
            continue
        out.append(f"    static let {sw} = Color(\"{name}\", bundle: .module)")
        ns.append(f"    static var {sw}: NSColor {{ NSColor(named: \"{name}\", bundle: .module)! }}")
    out.append("}")
    out.append("")
    ns.append("}")
    grads = [n for n in sorted(toks) if "gradient" in (toks[n]["light"] or {})]
    g = ["public extension Gradient {"]
    for n in grads:
        stops = ", ".join(f"Color(tokenHex: 0x{h[1:]})" for h in toks[n]["light"]["gradient"])
        g.append(f"    /// `{n}` (top → bottom).")
        g.append(f"    static let {camel(n)} = Gradient(colors: [{stops}])")
    g.append("}")
    return "\n".join(out + ns + [""] + g) + "\n"


# ---------------------------------------------------------------- typography

WEIGHTS = {"regular", "medium", "semibold", "bold"}


def typography(secs) -> list[dict]:
    out = []
    for cells in table_rows(secs.get("2", [])):
        names = keys_in(cells[0])
        if cells[0].startswith("Markdown headings"):
            for lvl, size, line, w in re.findall(r"(h\d)\s+(\d+)/(\d+)\s+(\w+)", cells[1]):
                out.append({"name": f"type.markdown.{lvl}", "size": int(size), "line": int(line),
                            "weight": w, "tracking": 0.0, "mono": False, "use": f"Markdown {lvl}"})
            continue
        if not names:
            continue
        m = re.match(r"(\d+)\s*/\s*(\d+)", cells[1])
        if not m:
            continue  # type.math follows type.body
        wcell = cells[2].lower()
        weight = next((w for w in WEIGHTS if w in wcell.split()), "regular")
        tr = cells[3].replace("−", "-").replace("+", "")
        out.append({"name": names[0], "size": int(m.group(1)), "line": int(m.group(2)), "weight": weight,
                    "tracking": float(tr) if re.fullmatch(r"-?\d+(\.\d+)?", tr) else 0.0,
                    "mono": "mono" in wcell, "use": cells[4] if len(cells) > 4 else ""})
    return out


