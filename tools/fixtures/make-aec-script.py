#!/usr/bin/env python3
"""M3.T12 AT-280 AC1: fixtures/audio/aec-10min/ — the 10-minute scripted conversation for the speaker test.

20 user questions = fixtures/audio/dictation/q01–q20 (LibriSpeech test-clean read speech, 16 kHz mono), referenced
by relative path (no copied audio, no new LFS objects), in order, with their reference text. Timing is not fixed in
the script: the harness (`AntiChat -Bench aec`) plays each question 1 s after the previous reply finished, so a
question never overlaps the assistant's speech; ~10 min = 20 × (question + reply + gaps). The task's Kokoro-
synthesised fillers are not used: the replies of the real chat model fill the time between questions.

  python3 -I tools/fixtures/make-aec-script.py [--fixtures fixtures]          # writes script.json + SOURCES.md
  python3 -I tools/fixtures/make-aec-script.py --fixtures fixtures verify     # regenerates in memory, compares
"""
import argparse
import json
import os
import sys
import wave


def build(fx):
    d = os.path.join(fx, "audio", "dictation")
    qs = []
    for i in range(1, 21):
        name = f"q{i:02d}"
        wav = os.path.join(d, name + ".wav")
        with wave.open(wav) as w:
            dur = w.getnframes() / w.getframerate()
        text = open(os.path.join(d, name + ".txt")).read().strip()
        qs.append({"wav": f"../dictation/{name}.wav", "text": text, "duration_s": round(dur, 3)})
    script = {"version": 1, "gap_after_reply_s": 1.0, "questions": qs}
    total = sum(q["duration_s"] for q in qs)
    sources = (
        "# aec-10min (M3.T12, AT-280 AC1)\n\n"
        "The scripted conversation for the built-in speaker test (`tools/voice/aec-10min.sh`).\n\n"
        "- `script.json`: 20 user questions in order = `../dictation/q01–q20.wav` (LibriSpeech test-clean, CC BY 4.0;"
        " see `../dictation/SOURCES.md`) with their reference text and duration.\n"
        f"- Questions total {total:.1f} s; the harness plays each one with `afplay` 1 s after the previous reply"
        " finished (never over the assistant's speech); the real chat model's spoken replies fill the ~10 minutes.\n"
        "- Generated by `python3 -I tools/fixtures/make-aec-script.py`; `verify` regenerates and compares.\n"
    )
    return json.dumps(script, indent=2) + "\n", sources


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixtures", default=os.environ.get("ANTICHAT_FIXTURES", "fixtures"))
    ap.add_argument("cmd", nargs="?", default="make")
    a = ap.parse_args()
    script, sources = build(a.fixtures)
    out = os.path.join(a.fixtures, "audio", "aec-10min")
    if a.cmd == "verify":
        ok = open(os.path.join(out, "script.json")).read() == script and open(os.path.join(out, "SOURCES.md")).read() == sources
        print("aec-10min:", "ok" if ok else "MISMATCH")
        sys.exit(0 if ok else 1)
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "script.json"), "w").write(script)
    open(os.path.join(out, "SOURCES.md"), "w").write(sources)
    print("wrote", out)


if __name__ == "__main__":
    main()
