"""tools/vendor-sync implementation (P-platform-16; upstream.md §3–§4; M0.T02/T14).

Layout per donor (Vendor/donors.json):
  Vendor/.upstream/<name>@<short>/<upstream path>   pristine, written by `vendir sync`
  Vendor/<name>@<short>/<upstream path>             compiled copy (allow-listed `vendored`/`test` rows only)
  Vendor/<name>-allowlist.tsv                       mode \t upstream path \t reason (P-IDs or `closure: <Type>`)
  Vendor/<name>@<short>/access-rewrite.txt          <upstream path>:<pristine line>:<decl name> (UP-OS-000)
Modes: `vendored` (compiled into the target), `test` (compiled into the test target), `watch`
(pristine only, for `report --ports`; ported/reference files).
"""
from __future__ import annotations

import difflib
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VENDOR = ROOT / "Vendor"
VENDIR = ROOT / ".tools/bin/vendir"
MARK = re.compile(r"ANTICHAT-PATCH: (UP-[A-Z]+-\d{3})\b")
END = "ANTICHAT-PATCH-END"
META_FILES = {"ORIGIN", "LICENSE", "access-rewrite.txt"}


def die(msg: str, code: int = 1) -> None:
    print(f"vendor-sync: {msg}", file=sys.stderr)
    sys.exit(code)


def donors() -> dict:
    return json.loads((VENDOR / "donors.json").read_text())


def donor(name: str) -> dict:
    d = donors().get(name) or die(f"unknown donor {name}")
    d = dict(d)
    d["name"] = name
    d["short"] = d["ref"][:7]
    d["pristine"] = VENDOR / ".upstream" / f"{name}@{d['short']}"
    d["compiled"] = VENDOR / f"{name}@{d['short']}"
    return d


def allowlist(d: dict) -> list[tuple[str, str, str]]:
    rows = []
    for line in (VENDOR / f"{d['name']}-allowlist.tsv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        mode, path, reason = (line.split("\t") + ["", ""])[:3]
        if mode not in ("vendored", "test", "watch"):
            die(f"bad mode {mode!r} in allowlist: {line}")
        rows.append((mode, path, reason))
    return rows


def compiled_paths(d: dict, modes=("vendored", "test")) -> list[str]:
    return [p for m, p, _ in allowlist(d) if m in modes]


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


# ------------------------------------------------------------------ vendir
def gen_vendir() -> None:
    lines = ["# GENERATED by `tools/vendor-sync gen-vendir` from Vendor/donors.json + Vendor/<name>-allowlist.tsv.",
             "# Do not edit by hand (upstream.md §3.2).",
             "apiVersion: vendir.k14s.io/v1alpha1", "kind: Config", "directories:"]
    for name in donors():
        d = donor(name)
        # No `depth`: vendir's shallow fetch only reaches branch/tag tips, so a pinned sha stops syncing once
        # upstream moves past it (found in the M0.T03 rehearsal).
        if d.get("github_release"):  # M2.T16: release asset (sqlite-vec amalgamation); `ref` = the tag's commit
            gr = d["github_release"]
            lines += [f"- path: Vendor/.upstream/{name}@{d['short']}", "  contents:", "  - path: .",
                      "    githubRelease:", f"      slug: {gr['slug']}", f"      tag: {gr['tag']}",
                      f"      assetNames: [{gr['asset']}]", f"      unpackArchive: {{path: {gr['asset']}}}",
                      "      disableAutoChecksumValidation: true", "    includePaths:"]
            lines += [f"    - {p}" for _, p, _ in sorted(allowlist(d), key=lambda r: r[1])]
            continue
        lines += [f"- path: Vendor/.upstream/{name}@{d['short']}", "  contents:", "  - path: .",
                  f"    git: {{url: {d['repo']}, ref: {d['ref']}}}", "    includePaths:"]
        lines += [f"    - {p}" for _, p, _ in sorted(allowlist(d), key=lambda r: r[1])]
        lines += [f"    - {p}" for p in d.get("extra_include", [])]
        if d.get("exclude"):
            lines += ["    excludePaths:"] + [f"    - {p}" for p in d["exclude"]]
    (VENDOR / "vendir.yml").write_text("\n".join(lines) + "\n")


def vendir_sync(locked: bool = False, chdir: Path = ROOT) -> None:
    if not VENDIR.is_file():
        die(f"{VENDIR.relative_to(ROOT)} missing (run tools/bootstrap.sh, step 3)")
    cmd = [str(VENDIR), "sync", "--chdir", str(chdir), "-f", "Vendor/vendir.yml", "--lock-file", "Vendor/vendir.lock.yml"]
    if locked:
        cmd.append("--locked")
    subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL if chdir != ROOT else None)


# ------------------------------------------------------------------ access rewrite
DECL = re.compile(r"^(\s*)((?:@\w+(?:\([^)]*\))?\s+)*)((?:(?:final|nonisolated|indirect|override|static|class|"
                  r"convenience|required|mutating|lazy|weak|unowned|dynamic|internal|package|public|open|private|"
                  r"fileprivate)\s+)*)(.*)$")


def rewrite_line(line: str) -> str:
    m = DECL.match(line)
    if not m:
        return line
    indent, attrs, mods, rest = m.groups()
    words = mods.split()
    if any(w in words for w in ("package", "public", "open")):
        return line
    if any(w in words for w in ("private", "fileprivate")):
        die(f"access-rewrite on a private declaration: {line.strip()}")
    if "internal" in words:
        mods = re.sub(r"\binternal\b", "package", mods, count=1)
        return f"{indent}{attrs}{mods}{rest}"
    return f"{indent}{attrs}package {mods}{rest}"


def access_entries(d: dict) -> list[tuple[str, int, str]]:
    f = d["compiled"] / "access-rewrite.txt"
    out = []
    if f.exists():
        for line in f.read_text().splitlines():
            if line.strip() and not line.startswith("#"):
                path, ln, name = line.rsplit(":", 2)
                out.append((path, int(ln), name))
    return out


DECL_OF = r"\b(?:let|var|func|class|struct|enum|actor|protocol|typealias|case|init)\s+{}\b"


def apply_access(text: str, pristine: str, entries: list[tuple[int, str]]) -> str:
    """Rewrite each pristine line `ln` (1-based) at its occurrence in `text` nearest to the same
    relative position (patches shift lines; identical lines elsewhere must not be hit)."""
    plines = pristine.splitlines(keepends=True)
    lines = text.splitlines(keepends=True)
    for ln, name in entries:
        src = plines[ln - 1]
        if not re.search(DECL_OF.format(re.escape(name)), src):
            die(f"access-rewrite: line {ln} does not declare {name}: {src.strip()}")
        new = rewrite_line(src.rstrip("\n")) + ("\n" if src.endswith("\n") else "")
        # Occurrences of the pristine line in pristine before ln → pick the same occurrence index.
        nth = sum(1 for l in plines[: ln - 1] if l == src)
        hits = [i for i, l in enumerate(lines) if l == src or l == new]
        if len(hits) <= nth:
            die(f"access-rewrite: {name} (pristine line {ln}) not found in the compiled copy; a patch block "
                f"changed it, so move the access change into that block")
        lines[hits[nth]] = new
    return "".join(lines)


def expected_unpatched(d: dict, path: str) -> str:
    """Pristine text with only the mechanical access rewrite applied (what an unpatched file looks like)."""
    pristine = (d["pristine"] / path).read_text()
    ents = [(ln, n) for p, ln, n in access_entries(d) if p == path]
    return apply_access(pristine, pristine, ents) if ents else pristine


def access_rewrite(d: dict) -> None:
    by_file: dict[str, list[tuple[int, str]]] = {}
    for p, ln, n in access_entries(d):
        by_file.setdefault(p, []).append((ln, n))
    for p, ents in by_file.items():
        tgt = d["compiled"] / p
        new = apply_access(tgt.read_text(), (d["pristine"] / p).read_text(), ents)
        tgt.write_text(new)


# ------------------------------------------------------------------ materialize
def materialize(d: dict) -> None:
    want = set(compiled_paths(d))
    d["compiled"].mkdir(parents=True, exist_ok=True)
    for p in sorted(want):
        src, dst = d["pristine"] / p, d["compiled"] / p
        if not src.exists():
            die(f"{p} not in {d['pristine']} (run `vendor-sync sync`)")
        if not dst.exists():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
    for f in sorted(d["compiled"].rglob("*")):
        rel = str(f.relative_to(d["compiled"]))
        if f.is_file() and rel not in want and rel not in META_FILES:
            print(f"remove {rel} (no longer allow-listed)")
            f.unlink()
    for dirpath, dirnames, filenames in os.walk(d["compiled"], topdown=False):
        if not dirnames and not filenames:
            os.rmdir(dirpath)
    lic = d["pristine"] / "LICENSE"
    if lic.exists():
        shutil.copy2(lic, d["compiled"] / "LICENSE")
    n = len(want)
    lock = (VENDOR / "vendir.lock.yml").read_text() if (VENDOR / "vendir.lock.yml").exists() else ""
    fetched = datetime.now(timezone.utc).date().isoformat() if d["ref"] not in lock else _origin_date(d)
    ups = sorted({m for f in d["compiled"].rglob("*") if f.suffix in (".swift", ".py")
                  for m in MARK.findall(f.read_text())})
    (d["compiled"] / "ORIGIN").write_text(
        f"name: {d['name']}\nrepo: {d['repo']}\nref: {d['ref']}\nfetched: {fetched} (vendir.lock.yml)\n"
        f"license: {d['license']}  (LICENSE copied to ./LICENSE)\n"
        f"paths: see Vendor/{d['name']}-allowlist.tsv (vendored + test rows; {n} files)\n"
        f"patches: {', '.join(ups) if ups else 'none'} (Vendor/UPSTREAM_PATCHES.md)\n"
        f"access-rewrite: internal→package on declarations listed in access-rewrite.txt "
        f"(UP-OS-000, mechanical, re-applied by vendor-sync)\n")
    access_rewrite(d)
    gen_package()


def _origin_date(d: dict) -> str:
    o = d["compiled"] / "ORIGIN"
    if o.exists():
        m = re.search(r"^fetched: (\S+)", o.read_text(), re.M)
        if m:
            return m.group(1)
    return datetime.now(timezone.utc).date().isoformat()


# ------------------------------------------------------------------ Package.swift source lists
def gen_package() -> None:
    """Rewrite the generated `sources:` blocks in Package.swift from the allow-lists."""
    pkg = ROOT / "Package.swift"
    text = pkg.read_text()
    for name in donors():
        d = donor(name)
        if "target" not in d or d.get("github_release"):  # resource donor / C release donor (no generated list) (e.g. FastVideo Python, copied into a runtime, not compiled)
            continue
        prefix = d.get("root", "Packages/OsaurusCore") + "/"
        for mode, tag in (("vendored", d["target"]), ("test", d.get("test_target"))):
            if tag is None:  # e.g. LetsMove (M10.T02): an ObjC target without ported upstream tests
                continue
            paths = sorted(p[len(prefix):] if mode == "vendored" else p[len(prefix) + len("Tests/"):]
                           for p in compiled_paths(d, (mode,)))
            body = "".join(f'    "{p}",\n' for p in paths)  # ends with a newline before END
            pat = re.compile(rf"(// BEGIN GENERATED {tag} sources[^\n]*\n).*?(\s*// END GENERATED {tag} sources)", re.S)
            if pat.search(text):
                text = pat.sub(lambda m: m.group(1) + body + m.group(2).lstrip("\n").lstrip(" ").rjust(len(m.group(2).lstrip("\n").lstrip(" ")) + 4), text)
    pkg.write_text(text)


# ------------------------------------------------------------------ VENDORED.json
# M1.T17: a `watch` row is listed as a watch-only port entry once AntiChat code cites it in a port header
# (`<owner>/<repo>@<short>:<upstream path>`, the acknowledgments `Ported from` form); `ported_to` names the citing files.
def _port_citations() -> list[tuple[str, str]]:
    out = []
    for top in ("App", "Packages"):
        for f in sorted((ROOT / top).rglob("*.swift")):
            if ".build" in f.parts:
                continue
            try:
                out.append((str(f.relative_to(ROOT)), f.read_text(errors="replace")[:6000]))
            except OSError:
                pass
    return out


def vendored_json() -> dict:
    files = []
    citations = None
    for name in donors():
        d = donor(name)
        acc = {p for p, _, _ in access_entries(d)}
        slug = "/".join(d["repo"].rstrip("/").removesuffix(".git").split("/")[-2:])
        for mode, p, reason in allowlist(d):
            if mode == "watch":
                citations = _port_citations() if citations is None else citations
                needle = f"{slug}@{d['short']}:{p}"
                ported = [rel for rel, text in citations if needle in text]
                if ported:
                    pristine = d["pristine"] / p
                    files.append({"donor": name, "sha": d["ref"], "mode": "watch", "upstream_path": p,
                                  "local_path": str(pristine.relative_to(ROOT)), "license": d["license"],
                                  "upstream_sha256": sha256(pristine), "local_sha256": None, "patches": [],
                                  "used_by": [x for x in re.split(r"[,\s]+", reason) if x.startswith("P-")],
                                  "reason": reason, "ported_to": ported})
                continue
            local = d["compiled"] / p
            ups = sorted(set(MARK.findall(local.read_text(errors="replace")))) if local.exists() else []  # UTF-16 .strings (LetsMove)
            if p in acc:
                ups = ["UP-OS-000"] + ups
            files.append({"donor": name, "sha": d["ref"], "mode": mode, "upstream_path": p,
                          "local_path": str(local.relative_to(ROOT)), "license": d["license"],
                          "upstream_sha256": sha256(d["pristine"] / p),
                          "local_sha256": sha256(local) if local.exists() else None, "patches": ups,
                          "used_by": [x for x in re.split(r"[,\s]+", reason) if x.startswith("P-")],
                          "reason": reason})
    # M1.T09: npm dist files copied by `make vendor-js` (tools/vendor/vendor-js.py writes Vendor/js/vendored-js.json).
    js = VENDOR / "js/vendored-js.json"
    if js.exists():
        for e in json.loads(js.read_text())["files"]:
            files.append({"donor": f"npm:{e['package']}", "sha": e["version"], "mode": "vendored-js",
                          "upstream_path": e["upstream_path"], "local_path": e["local_path"], "license": e["license"],
                          "upstream_sha256": e["sha256"], "local_sha256": sha256(ROOT / e["local_path"]),
                          "integrity": e["integrity"], "patches": [], "used_by": e["used_by"],
                          "reason": ", ".join(e["used_by"])})
    # M6.T09: Noto fonts downloaded by `make vendor-fonts` (tools/vendor/vendor-fonts.py writes vendored-fonts.json).
    fonts = VENDOR / "fonts/vendored-fonts.json"
    if fonts.exists():
        for e in json.loads(fonts.read_text())["files"]:
            files.append({"donor": f"fonts:{e['repo']}", "sha": e["sha"], "mode": "vendored-font",
                          "upstream_path": e["upstream_path"], "local_path": e["local_path"], "license": e["license"],
                          "upstream_sha256": e["sha256"], "local_sha256": sha256(ROOT / e["local_path"]),
                          "patches": [], "used_by": e["used_by"], "reason": ", ".join(e["used_by"])})
    return {"generated_by": "tools/vendor-sync vendored-json", "files": files}


def write_vendored_json() -> None:
    (VENDOR / "VENDORED.json").write_text(json.dumps(vendored_json(), indent=1, ensure_ascii=False) + "\n")


# ------------------------------------------------------------------ verify / closure-check
def verify() -> int:
    rc = 0
    if os.environ.get("OFFLINE") == "1" or "--offline" in sys.argv:
        print("[skip] vendir sync --locked re-fetch (offline)")
    else:
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / "Vendor").mkdir()
            for f in ("vendir.yml", "vendir.lock.yml"):
                shutil.copy2(VENDOR / f, Path(tmp) / "Vendor" / f)
            vendir_sync(locked=True, chdir=Path(tmp))
            a, b = Path(tmp) / "Vendor/.upstream", VENDOR / ".upstream"
            fa = {str(p.relative_to(a)): sha256(p) for p in a.rglob("*") if p.is_file()}
            fb = {str(p.relative_to(b)): sha256(p) for p in b.rglob("*") if p.is_file()}
            if fa != fb:
                for k in sorted(set(fa) | set(fb)):
                    if fa.get(k) != fb.get(k):
                        print(f"pristine mismatch: {k}")
                rc = 1
            else:
                print(f"[ok] Vendor/.upstream matches vendir sync --locked ({len(fa)} files)")
    cur = json.loads((VENDOR / "VENDORED.json").read_text())
    if cur != vendored_json():
        print("VENDORED.json is stale (run `tools/vendor-sync vendored-json`)")
        rc = 1
    else:
        print(f"[ok] VENDORED.json current ({len(cur['files'])} files)")
    for name in donors():
        d = donor(name)
        for p in compiled_paths(d):
            if not (d["compiled"] / p).exists():
                print(f"compiled copy missing: {d['compiled'].name}/{p}")
                rc = 1
    r = subprocess.run([sys.executable, "-I", str(ROOT / "tools/ci/patch-lint.py")])
    return rc or r.returncode


def closure_check(name: str, tests: bool = False) -> int:
    """Build the donor target alone in a generated package (build/vendor-closure/<name>/, Vendor/ symlinked),
    so neither the rest of AntiChatKit nor its engine dependencies are resolved or built; with --tests also
    run the ported upstream tests. Lists the allow-listed files and, on failure, the missing types."""
    d = donor(name)
    pkg = ROOT / "build" / "vendor-closure" / name
    pkg.mkdir(parents=True, exist_ok=True)
    link = pkg / "Vendor"
    if link.is_symlink() or link.exists():
        link.unlink()
    link.symlink_to(VENDOR)
    prefix = d.get("root", "Packages/OsaurusCore") + "/"
    src = sorted(p[len(prefix):] for p in compiled_paths(d, ("vendored",)))
    tst = sorted(p[len(prefix) + len("Tests/"):] for p in compiled_paths(d, ("test",)))
    q = lambda xs: ",\n".join(f'        "{x}"' for x in xs)
    base = f"Vendor/{d['compiled'].name}/{prefix.rstrip('/')}"
    (pkg / "Package.swift").write_text(
        "// swift-tools-version: 6.2\n// GENERATED by `tools/vendor-sync closure-check` (donor target in isolation).\n"
        "import PackageDescription\n\nlet package = Package(\n"
        f'    name: "{d["target"]}Closure",\n    platforms: [.macOS("26.0")],\n    targets: [\n'
        f'        .target(name: "{d["target"]}", path: "{base}", sources: [\n{q(src)}\n        ],\n'
        "            swiftSettings: [.swiftLanguageMode(.v6)]),\n"
        f'        .testTarget(name: "{d["test_target"]}", dependencies: ["{d["target"]}"], path: "{base}/Tests", '
        f"sources: [\n{q(tst)}\n        ],\n            swiftSettings: [.swiftLanguageMode(.v6)]),\n    ]\n)\n")
    print(f"closure-check {name}@{d['short']}: {len(src)} vendored + {len(tst)} test files")
    cmd = ["swift", "test" if tests else "build", "--disable-keychain", "--package-path", str(pkg)]
    r = subprocess.run(cmd + ([] if tests else ["--target", d["target"]]), capture_output=True, text=True)
    sys.stdout.write(r.stdout[-20000:])
    sys.stderr.write(r.stderr[-20000:])
    if r.returncode:
        # Missing types live in files outside the allow-list, so search the full upstream tree at the ref.
        with tempfile.TemporaryDirectory() as t:
            subprocess.run(f"git -C '{_mirror(d)}' archive {d['ref']} {prefix.rstrip('/')} | tar -x -C '{t}'",
                           shell=True, check=False)
            mt = subprocess.run([sys.executable, "-I", str(ROOT / "tools/vendor/missing-types.py"), "--repo",
                                 str(Path(t) / prefix.rstrip("/"))], input=r.stdout + r.stderr, capture_output=True,
                                text=True)
        if mt.stdout.strip():
            print("closure grew? missing symbols (symbol, defining upstream file, DENY, first user):\n" + mt.stdout)
    return r.returncode


# ------------------------------------------------------------------ report / bump (upstream.md §4; rehearsed in M0.T03)
def _mirror(d: dict) -> Path:
    cache = Path(os.environ.get("ANTICHAT_DEV_CACHE", Path.home() / "Library/Caches/AntiChat-dev")) / "vendor" / f"{d['name']}.git"
    if not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "clone", "--bare", "--filter=blob:none", "-q", d["repo"], str(cache)], check=True)
    else:
        subprocess.run(["git", "-C", str(cache), "fetch", "-q", "--tags", "origin", "+refs/heads/*:refs/heads/*"], check=True)
    return cache


def report(names: list[str], ports: bool) -> int:
    for name in names or list(donors()):
        d = donor(name)
        m = _mirror(d)
        head = subprocess.run(["git", "-C", str(m), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        modes = ("vendored", "test", "watch") if ports else ("vendored", "test")
        paths = [p for mo, p, _ in allowlist(d) if mo in modes]
        out = subprocess.run(["git", "-C", str(m), "diff", "--stat=200", d["ref"], head, "--", *paths],
                             capture_output=True, text=True, check=True).stdout
        print(f"## {name} {d['short']}..{head[:7]}\n{out or '(no changes in allow-listed files)'}")
    return 0


# Carry = the patched state the patches come from: a commit of this repo whose Vendor/ holds the donor at
# `upstream` (donors.json "carry": {"git": <sha>, "upstream": <donor sha>}). `backport` records it; a later
# `bump` takes files that (re-)enter the closure from it, so patches on files upstream added inside the
# rehearsal window are carried in when the file appears (M0.T03).
def _git_show(rev: str, path: str) -> str | None:
    r = subprocess.run(["git", "show", f"{rev}:{path}"], cwd=ROOT, capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def _carry(d: dict) -> dict | None:
    c = d.get("carry")
    if not c:
        return None
    short = c["upstream"][:7]
    rows = []
    for line in (_git_show(c["git"], f"Vendor/{d['name']}-allowlist.tsv") or "").splitlines():
        if line.strip() and not line.startswith("#"):
            mode, path, reason = (line.split("\t") + ["", ""])[:3]
            rows.append((mode, path, reason))
    acc = []
    for line in (_git_show(c["git"], f"Vendor/{d['name']}@{short}/access-rewrite.txt") or "").splitlines():
        if line.strip() and not line.startswith("#"):
            p, ln, n = line.rsplit(":", 2)
            acc.append((p, int(ln), n))
    return {"git": c["git"], "upstream": c["upstream"], "rows": rows, "access": acc,
            "header": [l for l in (_git_show(c["git"], f"Vendor/{d['name']}-allowlist.tsv") or "").splitlines()
                       if l.startswith("#")],
            "patched": lambda p: _git_show(c["git"], f"Vendor/{d['name']}@{short}/{p}"),
            "pristine": lambda p: _git_show(c["git"], f"Vendor/.upstream/{d['name']}@{short}/{p}"),
            "table": _git_show(c["git"], "Vendor/UPSTREAM_PATCHES.md")}


def _merge(ours: str, base: str, theirs: str, labels: tuple[str, str, str]) -> tuple[str, int]:
    """git merge-file -p; returns (merged text, conflict count; < 0 on error)."""
    with tempfile.TemporaryDirectory() as t:
        fs = []
        for n, txt in zip(("ours", "base", "theirs"), (ours, base, theirs)):
            f = Path(t) / n
            f.write_text(txt)
            fs.append(str(f))
        r = subprocess.run(["git", "merge-file", "-p", "-L", labels[0], "-L", labels[1], "-L", labels[2], *fs],
                           capture_output=True, text=True)
        return r.stdout, r.returncode


def _relocate(line: str, n: str, new_text: str | None, rank: int = 0) -> int | None:
    """Line number (1-based) in new_text of pristine line `line` declaring `n`. `rank` = how many identical lines
    precede it in the old pristine file, so `func search(` in three backends of one file keep their own line."""
    if new_text is None:
        return None
    newl = new_text.splitlines()
    same = [i + 1 for i, l in enumerate(newl) if l == line]
    if same:
        return same[rank] if rank < len(same) else same[0]
    return next((i + 1 for i, l in enumerate(newl)
              if re.search(DECL_OF.format(re.escape(n)), l) and not l.lstrip().startswith("//")), None)


def _upstream_tree(m: Path, sha: str) -> set[str]:
    return set(subprocess.run(["git", "-C", str(m), "ls-tree", "-r", "--name-only", sha], capture_output=True,
                              text=True, check=True).stdout.splitlines())


REHEARSAL_HDR = "\n\n### Not yet in the closure at "


def sync_patch_table(d: dict, carry: dict) -> list[str]:
    """Rehearsal only (donor has a `carry`): rows of UPSTREAM_PATCHES.md with no marker in the current compiled
    copy (their target code is not upstream yet at this ref) move under 'Not applied → Not yet in the closure',
    and rows whose marker is back move up again (ordered as in the carry's table), so patch-lint rule 1 holds.
    Starts from the current table, so rows added during the rehearsal are kept. Returns the inactive UP ids."""
    path = VENDOR / "UPSTREAM_PATCHES.md"
    text = path.read_text() if path.exists() else (carry["table"] or "")
    have = {up for f in d["compiled"].rglob("*.swift") for up in MARK.findall(f.read_text())}
    row_re = re.compile(r"^\| (UP-[A-Z]+-\d{3}) \| [^|]+ \| [^|]+ \| ([^|]+) \|")
    head, sep, tail = text.partition("## Not applied")
    tail, _, parked = tail.partition(REHEARSAL_HDR)
    parked_rows = [l for l in parked.splitlines(keepends=True) if row_re.match(l)]
    lines = head.splitlines(keepends=True)
    rows = [l for l in lines if row_re.match(l)] + parked_rows
    first = next((i for i, l in enumerate(lines) if row_re.match(l)), len(lines))
    last = max((i for i, l in enumerate(lines) if row_re.match(l)), default=first - 1)
    order = {m.group(1): i for i, m in enumerate(row_re.match(l) for l in (carry["table"] or "").splitlines()) if m}
    active = [l for l in rows if row_re.match(l).group(2).strip() == "access" or row_re.match(l).group(1) in have]
    active.sort(key=lambda l: order.get(row_re.match(l).group(1), len(order)))
    moved = [l for l in rows if l not in active]
    head = "".join(lines[:first] + active + lines[last + 1:])
    tail = tail.rstrip("\n") + "\n"
    if moved:
        tail = (tail.rstrip("\n") + REHEARSAL_HDR + f"{d['short']} (vendor-sync rehearsal; restored when its target "
                f"code enters)\n\n| UP id | Donor@sha | File | Kind | What | Why | Owner P | Upstreamable | "
                f"Upstream PR | Drop when |\n|---|---|---|---|---|---|---|---|---|---|\n" + "".join(moved))
    path.write_text(head + sep + tail)
    return [row_re.match(l).group(1) for l in moved]


def _retarget(name: str, new_ref: str, mode: str) -> int:
    """mode 'bump': 3-way merge the current compiled copy onto new_ref (files entering the closure come
    from the carry, if any). mode 'backport': every file comes from the carry/current head patched copy
    (ours = patched head, base = pristine head, theirs = pristine new_ref)."""
    d = donor(name)
    m = _mirror(d)
    new = subprocess.run(["git", "-C", str(m), "rev-parse", f"{new_ref}^{{commit}}"], capture_output=True, text=True,
                         check=True).stdout.strip()
    all_d = donors()
    if mode == "backport" and not d.get("carry"):
        head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain", "--", "Vendor", "Package.swift"], cwd=ROOT,
                               capture_output=True, text=True).stdout.strip()
        if dirty:
            die("backport needs a committed Vendor/ (the carry is read from HEAD)")
        all_d[name]["carry"] = {"git": head, "upstream": d["ref"]}
        d["carry"] = all_d[name]["carry"]
    carry = _carry(d)
    old_compiled, old_pristine, old_ref = d["compiled"], d["pristine"], d["ref"]
    old_rows = allowlist(d)
    old_paths = {p for _, p, _ in old_rows}
    tree = _upstream_tree(m, new)
    # Allow-list at new_ref: current rows still upstream, plus carry rows upstream that are not yet listed.
    rows = [r for r in old_rows if r[1] in tree] if mode == "bump" else []
    gone = [p for mo, p, _ in old_rows if p not in tree and mo != "watch"] if mode == "bump" else []
    if carry:
        listed = {r[1] for r in rows}
        rows += [r for r in carry["rows"] if r[1] in tree and r[1] not in listed]
        order = {r[1]: i for i, r in enumerate(carry["rows"])}
        rows.sort(key=lambda r: order.get(r[1], len(order)))
        dropped = [p for mo, p, _ in carry["rows"] if p not in tree and mo != "watch"]
    else:
        dropped = gone
    entered = [p for mo, p, _ in rows if p not in old_paths and mo != "watch"]
    all_d[name]["ref"] = new
    (VENDOR / "donors.json").write_text(json.dumps(all_d, indent=1) + "\n")
    al = VENDOR / f"{name}-allowlist.tsv"
    header = carry["header"] if carry else [l for l in al.read_text().splitlines() if l.startswith("#")]
    al.write_text("\n".join(header + ["\t".join(r) for r in rows]) + "\n")
    nd = donor(name)
    gen_vendir()
    vendir_sync()
    conflicts: list[tuple[str, int]] = []
    nd["compiled"].mkdir(parents=True, exist_ok=True)
    for p in compiled_paths(nd):
        dst = nd["compiled"] / p
        dst.parent.mkdir(parents=True, exist_ok=True)
        other = (nd["pristine"] / p).read_text()
        if mode == "bump" and p in old_paths and (old_compiled / p).exists():
            ours, base, lab = (old_compiled / p).read_text(), (old_pristine / p).read_text(), old_ref[:7]
        elif carry and carry["patched"](p) is not None:
            ours, base, lab = carry["patched"](p), carry["pristine"](p), carry["upstream"][:7]
        else:
            shutil.copy2(nd["pristine"] / p, dst)
            continue
        merged, rc = _merge(ours, base, other, ("ours", f"upstream@{lab}", f"upstream@{new[:7]}"))
        if rc < 0 or rc > 127:  # git merge-file error (it caps the conflict count at 127): never write its output
            die(f"git merge-file failed on {p} (exit {rc})")
        dst.write_text(merged)
        if rc:
            conflicts.append((p, rc))
    # access-rewrite.txt: relocate each declaration in the new pristine file by its text, keeping the layout
    # of the carry's file (or the current one): a declaration's source line is taken from the pristine copy
    # it was last applied to.
    acc_old = old_compiled / "access-rewrite.txt"
    # Keys are (path, name, occurrence) so two entries with the same name in one file stay distinct.
    def keyed(entries):
        seen: dict[tuple[str, str], int] = {}
        for p, ln, n in entries:
            i = seen.get((p, n), 0)
            seen[(p, n)] = i + 1
            yield (p, n, i), ln
    old_src: dict[tuple[str, str, int], str] = {}
    old_rank: dict[tuple[str, str, int], int] = {}
    if mode == "bump":
        for k, ln in keyed(access_entries(d)):
            if (old_pristine / k[0]).exists():
                lines = (old_pristine / k[0]).read_text().splitlines()
                old_src[k] = lines[ln - 1]
                old_rank[k] = lines[:ln - 1].count(lines[ln - 1])
    layout = ((_git_show(carry["git"], f"Vendor/{name}@{carry['upstream'][:7]}/access-rewrite.txt") if carry
               else acc_old.read_text() if acc_old.exists() else "") or "").splitlines()
    if carry and mode == "bump":  # keep entries added after the carry (they have no carry layout line)
        lk = {k for k, _ in keyed(tuple(l.rsplit(":", 2)[:1]) + (int(l.rsplit(":", 2)[1]), l.rsplit(":", 2)[2])
                                  for l in layout if l.strip() and not l.startswith("#"))}
        layout += [f"{k[0]}:{ln}:{k[1]}" for k, ln in keyed(access_entries(d)) if k not in lk]
    current = set(compiled_paths(nd))
    out = []
    seen_layout: dict[tuple[str, str], int] = {}
    for line in layout:
        if not line.strip() or line.startswith("#"):
            out.append(line)
            continue
        p, ln, n = line.rsplit(":", 2)
        occ = seen_layout.get((p, n), 0)
        seen_layout[(p, n)] = occ + 1
        if p not in current:
            continue
        src, rank = old_src.get((p, n, occ)), old_rank.get((p, n, occ), 0)
        if src is None:
            pr = carry["pristine"](p) if carry else None
            if not pr:
                die(f"access-rewrite: no pristine source for {p}:{ln}:{n}")
            prl = pr.splitlines()
            src = prl[int(ln) - 1]
            rank = prl[:int(ln) - 1].count(src)
        hit = _relocate(src, n, (nd["pristine"] / p).read_text(), rank)
        if hit is None:
            conflicts.append((f"access-rewrite {p}:{n}", -1))
            out.append(f"# LOST {p}:?:{n}")
        else:
            out.append(f"{p}:{hit}:{n}")
    (nd["compiled"] / "access-rewrite.txt").write_text("\n".join(out) + "\n")
    pkg = ROOT / "Package.swift"
    pkg.write_text(pkg.read_text().replace(f"Vendor/{old_compiled.name}/", f"Vendor/{nd['compiled'].name}/")
                   .replace(f'"Vendor/{old_compiled.name}"', f'"Vendor/{nd["compiled"].name}"'))  # root = "." (libxls)
    # Other hard-coded references (bridging headers, runtime builders, port citations) are listed, not rewritten.
    if old_compiled != nd["compiled"]:
        refs = subprocess.run(["git", "grep", "-l", f"{name}@{old_ref[:7]}", "--", ":!Vendor", ":!docs", ":!build",
                               ":!ACKNOWLEDGMENTS.md"], cwd=ROOT, capture_output=True, text=True).stdout.split()
        for r in refs:
            print(f"STALE-REF {r} still names {name}@{old_ref[:7]} (update after review)")
    if old_compiled != nd["compiled"]:
        shutil.rmtree(old_compiled)
        shutil.rmtree(old_pristine)
    inactive = sync_patch_table(nd, carry) if carry else []
    if conflicts:  # conflicted files are resolved by hand first; `finish` then materializes
        gen_package()
    else:
        materialize(nd)
        write_vendored_json()
    gen_vendir()
    print(f"{mode} {name} {old_ref[:7]} → {new[:7]}: {len(compiled_paths(nd))} compiled files, "
          f"{len(entered)} entered the closure, {len(conflicts)} conflicted, {len(dropped)} not upstream at {new[:7]}")
    for p in entered:
        print(f"ENTER {p}")
    for p, n in conflicts:
        print(f"CONFLICT {p} ({n})")
    for p in dropped:
        print(f"ABSENT {p}")
    for up in inactive:
        print(f"INACTIVE {up} (its files are not in the closure at {new[:7]})")
    if conflicts:
        print("resolve the conflicts, then run `tools/vendor-sync finish osaurus` (materialize + access-rewrite + "
              "VENDORED.json + patch-lint)")
        return 1
    lint = subprocess.run([sys.executable, "-I", str(ROOT / "tools/ci/patch-lint.py")]).returncode
    return 1 if lint or (gone and not carry) else 0


def _has_conflict_marker(text: str) -> bool:
    """Any line of a `git merge-file -L ours -L upstream@… -L upstream@…` conflict, not only the opening one."""
    return any(l == "<<<<<<< ours" or l.startswith(">>>>>>> upstream@") or l == "=======" for l in text.splitlines())


def finish(name: str) -> int:
    """After resolving a bump's conflicts: re-apply access-rewrite, regenerate VENDORED.json, run patch-lint."""
    d = donor(name)
    left = [str(f.relative_to(ROOT)) for f in d["compiled"].rglob("*") if f.is_file() and f.suffix in
            (".swift", ".h", ".m", ".c", ".py") and _has_conflict_marker(f.read_text(errors="replace"))]
    acc = d["compiled"] / "access-rewrite.txt"
    left += [f"access-rewrite.txt: {l}" for l in (acc.read_text().splitlines() if acc.exists() else [])
             if l.startswith("# LOST")]
    if left:
        print("\n".join(f"unresolved: {p}" for p in left))
        return 1
    materialize(d)
    write_vendored_json()
    carry = _carry(d)
    for up in sync_patch_table(d, carry) if carry else []:
        print(f"INACTIVE {up} (no marker in the closure at {d['short']})")
    return subprocess.run([sys.executable, "-I", str(ROOT / "tools/ci/patch-lint.py")]).returncode


def bump(name: str, new_ref: str, branch: bool = True) -> int:
    if branch:
        d = donor(name)
        new = subprocess.run(["git", "-C", str(_mirror(d)), "rev-parse", f"{new_ref}^{{commit}}"], capture_output=True,
                             text=True, check=True).stdout.strip()
        subprocess.run(["git", "checkout", "-b", f"vendor/{name}-{new[:7]}"], cwd=ROOT, check=True)
    return _retarget(name, new_ref, "bump")


def bump_from_renovate() -> int:
    """Renovate postUpgradeTask (renovate.json): Renovate has rewritten a donor's `ref` in donors.json, while
    Vendor/vendir.lock.yml and the Vendor/<name>@<short>/ directories still hold the old ref. Restore the old
    ref and run the normal 3-way `bump` (no new branch: Renovate owns it)."""
    lock = (VENDOR / "vendir.lock.yml").read_text()
    rc = 0
    for name in donors():
        d = donor(name)
        if d["compiled"].exists():
            continue
        old = None
        for entry in lock.split("- contents:")[1:]:
            if f"path: Vendor/.upstream/{name}@" in entry:
                m = re.search(r"sha: ([0-9a-f]{40})", entry)
                old = m.group(1) if m else None
        if not old:
            die(f"bump-from-renovate: no locked ref for {name} in vendir.lock.yml")
        new = d["ref"]
        all_d = donors()
        all_d[name]["ref"] = old
        (VENDOR / "donors.json").write_text(json.dumps(all_d, indent=1) + "\n")
        print(f"bump-from-renovate: {name} {old[:7]} → {new[:7]}")
        rc |= bump(name, new, branch=False)
    return rc


def backport(name: str, old_ref: str) -> int:
    return _retarget(name, old_ref, "backport")


