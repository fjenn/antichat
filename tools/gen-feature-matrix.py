#!/usr/bin/env python3
"""Render docs/research/01-reference/feature-matrix.md from registry/features.json.

The registry is the source of truth; this file is regenerated, never hand-edited.
Usage: python3 tools/gen-feature-matrix.py [--date YYYY-MM-DD]
"""
import argparse
import collections
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / "docs" / "research"
REG = ROOT / "registry" / "features.json"
OUT = ROOT / "01-reference" / "feature-matrix.md"

GAP_LABELS = {
    "tier": "Tier-gated (accounts observed: ChatGPT Plus, Claude Max)",
    "region": "Region-gated or invite-only",
    "retired": "Retired, sunset or superseded (e.g. the pre-unified Claude experience)",
    "other-platform": "Other platform (web-only, mobile/iOS, Windows, ChatGPT Classic, a separate extension)",
    "needs-fresh-account": "Needs a fresh, teen, linked or second account (first-run is docs-based per D-003)",
    "needs-web-signin": "Needs a chatgpt.com sign-in: personalization, memory and security pages live on the web, and the Chrome profile was a guest (web-diff.md)",
    "desktop-app-hidden-from-capture": "Claude desktop-only surface: Claude Desktop hides its windows from computer use, so only claude.ai web was observed",
    "voice-no-mic": "Voice in-call UI: the Chrome test browser had no microphone and the desktop app is hidden from capture",
    "out-of-scope-coding": "Codex / Claude Code only (out of AntiChat scope)",
    "would-change-account": "Not run because it would publish links, connect accounts, create tasks/skills or otherwise change the account",
    "not-reached": "Documented; content-dependent and not triggered in the live passes",
    "entry-only": "Observed as an entry point only, not exercised",
}
GAP_ORDER = list(GAP_LABELS)


def idkey(fid):
    m = re.match(r"F-(\d+)([a-z]?)", fid)
    return (int(m.group(1)), m.group(2))


def present(v):
    return v in ("observed", "documented")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default="2026-10-29")
    date = ap.parse_args().date
    feats = sorted(json.loads(REG.read_text()), key=lambda f: idkey(f["id"]))
    assert not any("verdict" in f for f in feats), "Phase 1 rows must not carry a verdict"
    L = []
    w = L.append
    w("# Reference feature matrix: ChatGPT vs Claude (Phase 1, observation only)")
    w("")
    w(f"**As of:** {date}. **Source of truth:** `registry/features.json` ({len(feats)} features, no verdicts). This file is generated by `tools/gen-feature-matrix.py`; edit the registry, not this file.")
    w("**Inputs:** `chatgpt/screen-catalog.md` §1–11 (live ChatGPT for macOS 26.1021.31345), `chatgpt/web-diff.md` (chatgpt.com, guest), `chatgpt/documented-features.md`, `claude/screen-catalog.md` §D–E (live claude.ai web, Max plan, Dutch UI), `claude/documented-features.md`.")
    w("**Presence values:** observed = seen live (ChatGPT: the macOS app, plus chatgpt.com where cited; Claude: claude.ai in Chrome, because Claude Desktop hides its windows from computer use); documented = official docs only; absent = docs or the live UI show it does not exist; unknown = no evidence either way.")
    w("**Confidence rule:** observed = High; ChatGPT documented/absent = Medium; Claude documented/absent = High (Low where the docs flag 'unverified'). A row takes the lowest of its known claims, with manual overrides where the catalog marks [to verify]/[INFERENCE] or a conflict stays open. Evidence uses `file§section`. Why a cell is not observed is in each row's `observation_gap` field (codes below).")
    w("")
    w("## Counts")
    w("")
    w("| Presence | ChatGPT | Claude |")
    w("|---|---|---|")
    for v in ("observed", "documented", "absent", "unknown"):
        w(f"| {v} | {sum(f['chatgpt'] == v for f in feats)} | {sum(f['claude'] == v for f in feats)} |")
    both = sum(present(f["chatgpt"]) and present(f["claude"]) for f in feats)
    cg_only = sum(present(f["chatgpt"]) and not present(f["claude"]) for f in feats)
    cl_only = sum(present(f["claude"]) and not present(f["chatgpt"]) for f in feats)
    neither = len(feats) - both - cg_only - cl_only
    obs_both = sum(f["chatgpt"] == "observed" and f["claude"] == "observed" for f in feats)
    conf = collections.Counter(f["confidence"] for f in feats)
    w("")
    w(f"Present in both: **{both}** (observed live in both: **{obs_both}**) · ChatGPT only: **{cg_only}** · Claude only: **{cl_only}** · present in neither (absent/unknown/retired): **{neither}**. Confidence: High {conf['High']}, Medium {conf['Medium']}, Low {conf['Low']}.")
    w("")
    areas = collections.OrderedDict()
    for f in feats:
        areas.setdefault(f["area"], []).append(f)
    w("| Area | Features | ChatGPT observed | ChatGPT documented | Claude observed | Claude documented | In both |")
    w("|---|---|---|---|---|---|---|")
    tot = collections.Counter()
    for a in sorted(areas, key=lambda a: min(idkey(f["id"]) for f in areas[a])):
        rows = areas[a]
        c = dict(n=len(rows), go=sum(r["chatgpt"] == "observed" for r in rows), gd=sum(r["chatgpt"] == "documented" for r in rows),
                 co=sum(r["claude"] == "observed" for r in rows), cd=sum(r["claude"] == "documented" for r in rows),
                 b=sum(present(r["chatgpt"]) and present(r["claude"]) for r in rows))
        tot.update(c)
        w(f"| {a} | {c['n']} | {c['go']} | {c['gd']} | {c['co']} | {c['cd']} | {c['b']} |")
    w(f"| **total** | **{tot['n']}** | **{tot['go']}** | **{tot['gd']}** | **{tot['co']}** | **{tot['cd']}** | **{tot['b']}** |")
    w("")

    def is_open(t):
        return "[unresolved]" in t or t.startswith("[docs-internal]")
    resolved = [f for f in feats if f["conflicts"] and not is_open(f["conflicts"])]
    open_ = [f for f in feats if f["conflicts"] and is_open(f["conflicts"])]
    w(f"## Conflicts resolved ({len(resolved)} docs-vs-observed; observed wins)")
    w("")
    w("| F-ID | Feature | Conflict and resolution |")
    w("|---|---|---|")
    for f in resolved:
        w(f"| {f['id']} | {f['title'].replace('|', '/')} | {f['conflicts'].replace('|', '/')} |")
    w("")
    w(f"### Conflicts still open ({len(open_)})")
    w("")
    for f in open_:
        w(f"- **{f['id']} {f['title']}:** {f['conflicts']}")
    w("")
    w("## Observation gaps (why a cell is not observed)")
    w("")
    w("Observation used one ChatGPT Plus account (macOS app; chatgpt.com only as a guest) and one Claude Max account (claude.ai web) on 2026-10-29. Nothing was deleted or purchased; test artifacts are disclosed in the catalogs.")
    w("")
    for prod, name in (("chatgpt", "ChatGPT"), ("claude", "Claude")):
        w(f"### {name}")
        w("")
        g = collections.defaultdict(list)
        for f in feats:
            code = f.get("observation_gap", {}).get(prod)
            if code:
                g[code].append(f)
        for code in GAP_ORDER:
            if g.get(code):
                items = "; ".join(f"{f['id']} {f['title']}" for f in g[code])
                w(f"- **{GAP_LABELS[code]}** ({len(g[code])}): {items}.")
        unk = [f["id"] for f in feats if f[prod] == "unknown"]
        w(f"- **Unknown (no {name} evidence in docs or live UI; usually a {'Claude' if prod == 'chatgpt' else 'ChatGPT'}-only element)** ({len(unk)}): {', '.join(unk)}.")
        w("")
    w("## Matrix by area")
    for a in sorted(areas, key=lambda a: min(idkey(f["id"]) for f in areas[a])):
        rows = areas[a]
        w("")
        w(f"### {a} ({len(rows)})")
        w("")
        w("| F-ID | Feature | ChatGPT | Claude | Tier | Where | Confidence |")
        w("|---|---|---|---|---|---|---|")
        for f in rows:
            cells = [f["id"], f["title"], f["chatgpt"], f["claude"], f["tier"], f["location"], f["confidence"]]
            w("| " + " | ".join(str(c).replace("|", "\\|") for c in cells) + " |")
    w("")
    w("## Not mapped to features")
    w("")
    w("- `chatgpt/screen-catalog.md` \"Teardown obstacles\", \"Test artifacts\" and §9 (pattern summary); `claude/screen-catalog.md` D.17 and test-artifact lists: method notes and principles, not product elements.")
    w("- AntiChat relevance notes in the catalogs: intentionally not carried over (Phase 1 records no verdicts).")
    w("- Tier matrices (`documented-features.md` §8 in both files): folded into each row's `tier` field.")
    w("- Verbatim copy: `copy-reference.md`. Timing rules: `interaction-specs.md`.")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main()
